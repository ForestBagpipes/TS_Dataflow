# -*- coding: utf-8 -*-
"""Contributions, figure caption and chapter transitions.

Five parallel contributions gave the reader no way to tell which one carries the
paper. Three remain, one framing claim and two that support it. The figure
caption repeated the opening paragraph almost word for word and now only reads
the figure.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import (count_math, delete_paragraph, find_paragraph,
                          set_paragraph_md)

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)
    drop = []

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 图注只读图，不重复正文
    rw("图 1 用两个来自同一语料的窗口说明方法要解决的问题",
       "图 1 中的两个窗口来自同一份语料，波形上几乎一致。"
       "上方是传感器故障造成的孤立尖峰，去尖峰算子把它修回邻域水平，模型误差随之下降。"
       "下方是一次真实发生的极端峰值，同一个算子会把它一并削平，模型误差同样下降。"
       "两次动作在效用读数上分不开，"
       "能把它们分开的是峰值前后的局部结构在编辑之后是否保持一致。"
       "IntroAct-TS 在副本上完成试执行与重测，据此对两者作出相反的裁决。")

    # 贡献压到三条
    rw("（1）把时序数据治理形式化为屏蔽约束下的序贯干预决策",
       "（1）把时序数据治理形式化为屏蔽约束下的序贯干预决策，并给出对应的智能体 IntroAct-TS。"
       "该形式化把判定推迟到动作执行之后，"
       "因而不要求事先写出只关于动作本身的安全规则，"
       "同时使每一次判定都成为策略可用的反馈。"
       "安全与学习在这一设计中来自同一个决定，而不是两套彼此独立的机制。")
    rw("（2）提出以屏蔽作为奖励塑形器的策略学习机制",
       "（2）给出判定所需的双信号合取判据及其理论性质。"
       "结构条件不看模型意见，因而能够拦下通过抹平序列换取低误差的动作，"
       "其阈值由共形风险控制标定，使提交编辑的损害率获得有限样本的分布无关保证。"
       "本文进一步证明，把结构约束写成目标函数中的惩罚项时损害率存在不可消除的下界，"
       "而写成合取条件时没有这个下界，两种写法因此并不等价。")
    rw("（3）证明了探索过程的结构安全性",
       "（3）证明策略学习不以破坏语料为代价，并刻画了保证随学习推进的退化速率。"
       "由于候选动作在副本上执行且提交需经判定，"
       "对任意策略与任意探索强度，被提交编辑的结构失真都受同一阈值约束。"
       "策略更新会改变候选分布从而削弱共形标定所依赖的可交换性，"
       "本文给出两次标定之间保证退化的上界，"
       "它与标定间隔成正比、与已积累的访问次数成反比，为重新标定的频率提供了定量依据。")
    for p in ("（4）给出了屏蔽阈值的共形标定方法", "（5）建立了同时衡量数据质量与决策质量的评测体系"):
        drop.append(d.paragraphs[find_paragraph(d, p)])

    # 章节导航句去掉复述
    rw("本文余下部分的结构是",
       "本文余下部分先在第 1 章梳理相关研究，"
       "第 2 章交代判定所需的度量并把问题形式化，"
       "第 3 章按一次决策经过的四个环节给出方法与理论性质，"
       "第 4 章给出实验规划，第 5 章总结全文，第 6 章记录实现过程中遇到的问题。")

    # 第 1 章章首扣主线
    rw("与本文相关的研究分布在三个方向",
       "与本文相关的研究分布在三个方向。"
       "时序数据清洗提供了可用的动作集合，时序数据质量评估提供了判断样本价值的手段，"
       "智能体的策略学习与安全约束提供了在受限条件下改进决策的框架。"
       "前两个方向都停在动作执行之前，第三个方向提供的约束需要事先写定，"
       "本文要做的是把三者组织成一个能够在执行之后判定并从中学习的闭环。")

    # 结论回到主线
    rw("本文面向时序基础模型的语料治理问题",
       "本文面向时序基础模型的语料治理问题。"
       "一次修改是否有害取决于被修改的数据，因此无法在执行之前判定，"
       "本文的做法是把判定推迟到执行之后，并把执行放在副本上使判错的动作可以撤回。"
       "判定要求模型效用与时序结构两个相互独立的条件同时成立，"
       "结构条件不看模型意见，其阈值由共形风险控制标定到给定的损害率上。"
       "判定的结果同时是策略改进所用的反馈，"
       "而试错既然发生在副本上，学习过程本身就不修改语料。"
       "屏蔽因而承担双重职责，它拦下破坏性动作，也决定了哪些奖励能够到达策略，"
       "安全与学习由此来自同一个设计而不是两套机制。"
       "本文给出六条定理与一条命题及其证明，"
       "其中标定间隔内保证退化的上界把共形风险控制与策略的更新速率联系起来，"
       "为重新标定的频率提供了定量依据，"
       "而软惩罚的损害下界说明把结构约束写成目标函数中的一项与写成硬条件并不等价。")

    for p in drop:
        delete_paragraph(p)
    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"贡献与过渡改写完成，删除 {len(drop)} 段，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
