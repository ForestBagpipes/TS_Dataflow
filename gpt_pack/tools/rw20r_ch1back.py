"""Pull the later chapters back to the same register as the introduction.

The previous pass overcorrected into colloquial phrasing, so the survey read
like notes and the method read like commentary. The connectives and the sentence
functions from that pass are worth keeping. The vocabulary goes back to ordinary
academic prose.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    rw("三个方向的工作与本文有关",
       "本文的工作与三个方向相关。时序数据清洗提供了可供调用的动作集合，"
       "时序数据质量评估提供了衡量样本价值的手段，"
       "智能体的策略学习与安全约束提供了在受限条件下改进决策的框架。"
       "前两个方向的判定均发生在动作执行之前，第三个方向的安全约束需由专家事先写定，"
       "本文要做的是将三者组织成一个在执行之后判定并从判定中学习的闭环。")

    rw("这个方向上最成熟的想法是给数据划一条界",
       "约束驱动是这一方向最成熟的思路。"
       "SCREEN[5]假设相邻时间步的取值变化存在上下界，"
       "将违反约束的观测点修复至最近的合法取值，并给出线性时间的在线算法。"
       "SpeedAcc[7]在速度之外引入加速度约束，以二阶信息控制修复后的平滑程度。"
       "上述两项工作处理单变量序列，"
       "MTCSC[8]将速度约束与聚类相结合，借助维度之间的相关性提升修复精度，"
       "MTSClean[15]则同时使用行约束与列约束以覆盖更多错误形态。"
       "约束驱动方法的可解释性好，运行开销低，"
       "其代价在于约束本身来自领域知识，阈值设定得当与否直接决定修复质量。")
    rw("另一条路让数据自己说话",
       "另一条思路从统计模型出发。"
       "IMR[6]指出异常检测与异常修复是两个不同的问题，"
       "直接将检测结果作为修复依据效果很差，"
       "转而采用自回归模型逐点估计并迭代收敛，"
       "同时借助少量已知正确的观测点作为起始约束。"
       "这类方法对参数设定的敏感度低于约束驱动方法，"
       "但其所需的种子信息在无标签场景中并不容易获得。")
    rw("近两年有人把算子的编排交给了强化学习",
       "近期出现了将算子编排交由强化学习的尝试[13]，"
       "采用分层策略先判断问题类型再挑选具体算子，"
       "并在奖励中加入平滑度与改动幅度两项以抑制过度清洗。"
       "这一方向使策略能够从下游反馈中改进，"
       "但算子在训练过程中立即作用于原始数据，探索阶段的错误无法撤回，"
       "安全性只能体现在训练收敛后的期望意义上，对单个窗口并无保证。")

    rw("还有一类工作干脆不改数据",
       "数据估值提供了另一种视角，它不改动取值，只量化每个样本对模型的贡献。"
       "Data Shapley[9]用合作博弈中的 Shapley 值刻画样本价值，"
       "理论性质完备，但计算开销随样本数增长很快。"
       "Data-OOB[10]借助袋装模型的袋外估计将开销降至可接受范围，"
       "KNNShapley[16]则通过近邻结构给出闭式解。"
       "这些方法为独立同分布数据设计，用于时序数据时会忽略时间点之间的依赖。"
       "TimeInf[11]针对这一点作了修正，"
       "将影响函数定义在时间块上再聚合至单个时间点，"
       "从而在给出逐点分数的同时保留时序结构。")
    rw("也有工作把大模型的先验拉进来判断质量",
       "近期工作将大语言模型的先验引入质量判断。"
       "TSRating[12]从趋势、频率、幅度与模式四个维度获取成对比较，"
       "再用元学习将这些判断蒸馏为一个轻量评分器，使评级能力在多个领域之间迁移。"
       "该工作在十一个数据集上进行了验证，"
       "选取评分最高的一半样本训练下游模型即可接近全量训练的效果。")
    rw("这个方向交出来的东西始终是分数或者排序",
       "这一方向的产出始终是分数或排序。"
       "它能够指出哪些窗口存在问题，却无法说明这些窗口应当如何处理，"
       "也不具备检验某次处理是否有效的机制。"
       "当低分窗口中混有稀有但正确的模式时，按分数丢弃会将其一并去除。")

    rw("在约束下学决策是强化学习的老题目",
       "在受约束条件下学习决策是强化学习的经典课题。"
       "受约束马尔可夫决策过程[17]将安全要求写成期望意义上的约束，"
       "通过拉格朗日松弛与策略优化联合求解，"
       "其保证在训练收敛后成立，训练过程中仍可能违反约束。"
       "屏蔽机制[14]提供了另一条路径，在智能体与环境之间加入一层过滤，"
       "动作只有不违反规约时才被放行，因此安全性在每一步都成立而不依赖收敛。"
       "屏蔽将安全逻辑与策略优化解耦，底层学习算法可以自由选择，"
       "这一性质与本文的需求相吻合。"
       "区别在于屏蔽的规约通常由领域专家书写，"
       "而在数据治理中，一次编辑是否有害无法表达成仅关于该编辑本身的条件，"
       "本文因此将规约替换为一个需在执行后测量才能判定的复合条件。")
    rw("策略该做成什么样，取决于问题的规模",
       "在策略的具体形式上，本文的决策序列很短，多数窗口在一到三步内结束，"
       "状态经特征提取后维度不高，动作集合规模有限。"
       "这样的设定接近上下文老虎机，与长程决策问题存在明显距离。"
       "上下文老虎机在线性收益假设下已有成熟的上置信界算法与遗憾分析[18,19,20]，"
       "样本效率高且易于解释，本文因此采用这一族方法。")
    rw("阈值该卡在哪，统计这边有现成的工具",
       "统计侧的进展提供了标定屏蔽阈值的工具。"
       "共形风险控制[21]在可交换性假设下，"
       "为由阈值参数化的决策族给出有限样本的风险上界，不需要对数据分布作任何假设。"
       "Learn Then Test[22]将这一思路扩展至更一般的风险函数。"
       "这些框架的共同前提是被约束的信号可以充当有害性的合理代理，"
       "而本文面对的信号在部分区域内与有害性方向相反，"
       "因此不能只对其做标定，需与一个不依赖模型的条件合取之后再行标定。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"第 1 章回调完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
