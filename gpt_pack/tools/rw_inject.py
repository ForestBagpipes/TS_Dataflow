# -*- coding: utf-8 -*-
"""Document corrections that go with the injection change."""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, insert_after, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260819.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 3.3 注入不影响定理 3
    i = find_paragraph(d, "定理 3 是本文与算子立即生效的强化学习清洗方案的核心差异")
    insert_after(d, i, [
        "定理 3 的成立与候选的来源无关。证明只用到两点，动作作用于副本的拷贝，"
        "以及工作副本仅在三个条件同时成立时才被更新。"
        "候选由提议者生成还是由策略强制注入，都不改变这两点，"
        "因此对强制注入的候选，被提交编辑的结构失真同样受同一阈值约束。",
    ], template_idx=i)

    # 3.4 改掉乐观初始化填补盲区的说法
    rw("乐观初始化与重分段一列的取值之间存在一个需要说清的交互",
       "乐观初始化的作用范围有一个边界，实测把它暴露了出来。"
       "上置信界只在提议者给出的候选集内选择，乐观初值再高也无法选中没有被提出的动作。"
       "首次在两千窗口上运行学习循环时，簇 1 与簇 11 上的去噪访问次数为零，"
       "两簇合计 392 个窗口占语料百分之十九点六，"
       "原因是提议者的候选集由主导缺陷决定，而这些窗口的主导缺陷从不是噪声。"
       "乐观初始化作用在选择层，这里的盲区却在提议层，层次不对应，因而无效。"
       "本文为此引入强制候选注入，当某个画像簇与算子的组合没有任何观测时，"
       "以概率 p_inject 把该算子直接加入候选集，注入的候选照常经过沙箱与完整屏蔽。"
       "注入的候选取该算子最保守的参数，因为它探的是一个尚无信息的格子，"
       "不宜同时带上激进的设定。"
       "重分段一列的情形与此不同，它整列取全局均值 0.6095，低于空格的乐观初值 1.0，"
       "因此学习早期不会被选中。这是乐观初始化按设计驱动探索的结果，"
       "配合阶段零已经证明该算子没有簇级结构，早期不访问它不会损失可学的信息。")

    # 3.4 两类增益
    j = find_paragraph(d, "价值表按撤销原因分为三张")
    insert_after(d, j, [
        "策略学习相对固定规则的增益分两类。"
        "一类发生在既有候选之内，策略依据画像簇与撤销原因调整备选次序，"
        "把更可能通过屏蔽的动作排到前面。"
        "另一类是主动尝试提议者从不给出的选项，这是固定规则无论如何调整都做不到的，"
        "因为它的候选集完全由缺陷判断决定，判断不指向某个算子，该算子就永远没有机会。"
        "第二类增益需要注入机制才能兑现，也是策略能够学习这件事的本质意义所在。",
    ], template_idx=j)

    # 3.4 预算跳过判据
    k = find_paragraph(d, "预算分配建立在同一套价值估计之上")
    insert_after(d, k + 2, [
        "后验接近确定这一条需要用相对的方式表达。"
        "缺陷类型后验分布在五个假设之上，实测其最大值即使在被判为干净的窗口上也只到 0.554，"
        "按绝对阈值设在接近确定的位置将永远不会触发。"
        "区分已定与未定的是干净假设领先次高假设的幅度，"
        "因此判据取干净为最高后验且领先次高至少 1.5 倍。"
        "该判据在运行之前定死。这是唯一一处窗口可以不经屏蔽就被略过的地方，"
        "所以它要求的是一个领先幅度而不只是一个最大值。",
    ], template_idx=k)

    # 4.2 实验五预期修订
    rw("这一组检验按价值分配探测预算是否优于均匀分配",
       "这一组检验按价值分配探测预算是否优于均匀分配。"
       "固定语料总预算，比较均匀分配、按风险分数分配与本文按价值估计分配三种方式。"
       "曲线的横轴取计算开销，这样打分族可以一并参与，"
       "因为 Data Shapley 需要反复重训、TimeInf 需要海森向量积、本文的探测只做前向，"
       "三者的单位开销不同，按探测次数比较对打分族没有意义。"
       "按探测次数的版本另行给出，用于本文方法内部三种分配方式的对比。"
       "收益与代价必须同表呈现。八百个训练窗口上跳过 124 个，省下 663 次探测，"
       "而被跳过的窗口中有 24 个含真实污染，漏检率为百分之十九点四，"
       "按缺陷类型为重复片段 9 个、噪声 9 个、尖峰 6 个。"
       "只报节省不报漏检会让这一机制显得没有代价。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"文档修正完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
