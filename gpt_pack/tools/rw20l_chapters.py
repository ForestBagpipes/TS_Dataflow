# -*- coding: utf-8 -*-
"""Apply the reference paper's transition pattern to the remaining chapters.

Two habits are copied. Each章 opens by saying what it will settle and why that
follows from what came before, in one sentence rather than a table of contents.
Each concept or module is introduced by the difficulty it answers, stated as a
sentence that ends where the new thing has to begin.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 第 1 章章首
    rw("与本文相关的研究分布在三个方向",
       "本文的工作与三个方向相关。时序数据清洗提供了可以调用的动作集合，"
       "时序数据质量评估提供了衡量样本价值的手段，"
       "智能体的策略学习与安全约束提供了在受限条件下改进决策的框架。"
       "前两个方向的判定都发生在动作执行之前，第三个方向的安全约束需要由专家事先写定，"
       "本文要做的是把三者组织成一个在执行之后判定并从判定中学习的闭环。")

    # 第 2 章章首
    rw("一次编辑是否值得提交，取决于它在两个方向上的表现",
       "把判定推迟到执行之后，首先要回答判定依据从何而来。"
       "一次编辑是否值得提交，取决于它在两个方向上的表现，"
       "模型是否因此变得更容易处理这段数据，以及序列自身的结构是否被保住。"
       "这两个方向需要各自的度量，度量之后还需要一个位置来施加判断，"
       "以及一种在无标签条件下确定阈值的方法。"
       "本章交代这四者，说明所处理的噪声类型，"
       "再把治理问题形式化为屏蔽约束下的序贯决策，最后给出整体框架。")

    # 第 3 章章首
    rw("上一章把治理问题写成了带预算的受约束序贯决策",
       "上一章把治理问题写成了带预算的受约束序贯决策，"
       "余下的是这一决策在实现层面如何完成。"
       "一次决策要先在无标签条件下取得判断所需的证据，"
       "再在不破坏数据的前提下测出候选动作的后果，"
       "然后据此判定这次改动能否提交，"
       "最后让判定的结果反过来改进后续的选择。"
       "本章按这四个环节给出具体实现与相应的理论性质，最后分析时间复杂度。")

    # 3.5 复杂度节的引入
    rw("设语料窗口数为 ",
       "上述四个环节都要在十万量级的窗口上反复执行，因此需要说明整体开销。"
       r"设语料窗口数为 $N$，窗口长度为 $L$，模型池大小为 $M$，"
       r"每个窗口的平均动作尝试次数为 $T$，邻域大小为 $K$，画像簇数为 $J$，"
       r"单次模型前向的开销为 $C(L)$。"
       r"取证阶段中，画像提取的主要开销来自频谱分析与变点检测，为 $O(NL\log L)$，"
       r"行为探测需要对每个窗口在每个模型上做一次前向，为 $O(NMC(L))$，"
       r"同类邻居检索采用近似索引后为 $O(N\log N+NK)$。"
       r"试执行阶段中，每次候选动作包含一次算子执行与一次重测，为 $O(L+C(L))$，"
       r"该阶段总开销为 $O(NT(L+C(L)))$。"
       r"判定中结构失真的计算是纯统计操作，为 $O(L\log L)$，不涉及模型前向。"
       r"学习阶段的价值更新是常数时间操作，预算分配需要对窗口排序，为 $O(N\log N)$，"
       r"价值表的空间开销为 $O(J|\mathcal{A}|)$。"
       r"阈值标定在已缓存的损害记录上进行，为 $O(|\Lambda|N)$，其中 $|\Lambda|$ 为阈值网格大小。")

    # 第 5 章结论
    rw("本文面向时序基础模型的语料治理问题",
       "本文面向时序基础模型的语料治理问题，"
       "针对一次修改是否有害取决于被修改数据因而无法事先判定这一困难，"
       "提出了屏蔽强化学习驱动的智能体 IntroAct-TS。"
       "该方法把判定推迟到动作执行之后，并把执行放在工作副本的拷贝上，"
       "使判错的动作可以撤回。"
       "判定要求模型效用与时序结构两个相互独立的条件同时成立，"
       "其中结构条件不看模型意见，其阈值由共形风险控制标定到给定的损害率上，"
       "由此解决了判定依据本身存在偏差的问题。"
       "所有候选都在副本上执行，未通过判定的尝试不改变任何数据，"
       "由此解决了试错代价落在不可恢复对象上的问题。"
       "屏蔽因而承担双重职责，它拦下破坏性动作，也决定了哪些奖励能够到达策略，"
       "安全与学习出自同一个设计。"
       "本文给出六条定理与一条命题及其证明，"
       "其中标定间隔内保证退化的上界把共形风险控制与策略的更新速率联系起来，"
       "为重新标定的频率提供了定量依据，"
       "而软惩罚的损害下界说明把结构约束写成目标函数中的一项与写成硬条件并不等价。")

    # 第 6 章章首
    rw("方法与实验规划给出的是打算做到什么",
       "前面几章给出的是方法应当做到什么，本章记录实现过程中实际遇到了什么。"
       "已发现的问题分三类，"
       "一类是实现缺陷，定位之后现象随即消失，"
       "一类是设计取舍带来的固有限制，改不掉只能说明清楚，"
       "另一类源于实验设计本身，需要重新安排对照才能回答。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"各章过渡润色完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
