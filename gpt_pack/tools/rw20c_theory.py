"""Write the three reinforcement plans into the document.

Theorem 6 bounds how far the risk guarantee degrades between two calibrations.
A proposition separates the soft penalty from the hard condition on a mechanism
level rather than an implementation one. The peer calibration section states the
condition under which it pays off, and an experiment is added to test it.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import (count_math, find_paragraph, insert_after,
                          set_paragraph_md)

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 一 定理 6，可交换性退化的定量刻画，接在两点边界之后
    i = find_paragraph(d, "有两点边界")
    set_paragraph_md(d.paragraphs[i],
       "定理 4 的可交换性前提在策略固定时成立，而策略学习会持续改变候选动作的分布，"
       "使部署数据与早先的校准集不再可交换。"
       "工程上的处理是每隔一段时间重新标定，把两次标定之间的阈值视为固定值，"
       "但这样做没有回答两次标定之间保证退化了多少。下面的结论给出这一退化的上界。")
    insert_after(d, i, [
        r"定理 6（标定间隔内的保证退化）设风险函数取值于 $[0,1]$，"
        r"记校准时的候选分布为 $P$，某次决策时的候选分布为 $Q$，"
        r"两者的总变差距离为 $\mathrm{TV}(P,Q)$，则部署风险满足",
        r"$$\mathbb{E}_{Q}[L]\le\mathbb{E}_{P}[L]+\mathrm{TV}(P,Q)\le\alpha+\mathrm{TV}(P,Q)$$",
        r"进一步，若在两次标定之间发生 $T_{\mathrm{cal}}$ 次更新，"
        r"奖励截断上界为 $q$，各格子在此期间的最小访问计数为 $n_{\min}$，"
        r"且任意状态下最优动作与次优动作的置信上界之差不小于 $\gamma$，则",
        r"$$\mathrm{TV}(P,Q)\le\frac{2qT_{\mathrm{cal}}}{\gamma n_{\min}}$$",
        "证明的思路分三步。"
        "第一步用有界风险函数在两个分布上期望之差受总变差距离控制这一标准事实，"
        "结合定理 4 给出的校准分布上的保证，得到第一个不等式。"
        "第二步刻画价值表的变化，增量更新每次对某个格子的改变是奖励与当前估计之差除以访问计数，"
        "奖励经截断后有界，因此单次改变不超过截断上界与访问计数之比，"
        r"$T_{\mathrm{cal}}$ 次更新的累积改变不超过其 $T_{\mathrm{cal}}$ 倍。"
        "第三步把价值变化换算为分布变化，上置信界是确定性策略，"
        "动作分布只在两个动作的置信上界发生交叉时才改变，"
        r"而间隔条件保证价值改变量小于 $\gamma$ 时排序不会翻转，由此得到第二个不等式。",
        r"定理 6 说明保证的退化与标定间隔成正比、与已积累的访问次数成反比。"
        "学习早期访问次数少，同样的间隔带来的退化更大，因此早期应当标定得更密，"
        "随着访问次数积累，同样的间隔所对应的退化自动收窄。"
        r"这为 $T_{\mathrm{cal}}$ 的选取提供了依据，此前只有策略变化快时应当缩短这一定性说法。"
        r"需要指明该结论依赖间隔条件 $\gamma$ 为正。"
        "上置信界是确定性策略，排序一旦翻转动作分布就跳变，"
        r"若某个状态下两个动作的置信上界任意接近，则 $\gamma$ 趋于零而上界失效。"
        r"该条件在实测中是否成立需要检验，检验方式是统计各状态下 $\gamma$ 的经验分布，"
        "若其下尾接近零则结论应改用期望形式而不是最坏情况形式。这一检验尚未进行。",
        "另有一点边界与可交换性无关。阈值网格中最保守的取值仍然对应一个正的经验风险，"
        "低于这个下界的目标水平在当前动作空间下无解，"
        "此时标定过程返回最保守的阈值，这一行为符合定义。"
        "定理 3 给出的结构上界在两次标定之间始终成立，"
        "因此标定间隔只影响损害率保证的紧致程度，不影响结构安全性。",
    ], template_idx=i)

    # 二 命题 1，软惩罚的损害下界，接在定理 1 讨论之后
    j = find_paragraph(d, "定理 1 不依赖任何一个条件的判别力")
    insert_after(d, j, [
        "把结构信息以合取条件的形式引入，与把它作为目标函数中的惩罚项引入，"
        "两者的差别不止于形式。同期的清洗智能体采用后一种做法，"
        "即在效用增益中减去带系数的结构失真再按加权和取舍。"
        "下面的结论说明这两种做法在严格的损害预算下并不等价。",
        r"命题 1（软惩罚的损害下界）设软惩罚的接受判据为 "
        r"$\Delta U(a)-\mu D(x,a(x))>0$，其中 $\mu>0$ 为惩罚系数。"
        r"若存在一类窗口，其上有害动作的效用增益与结构失真之比不低于某个正数 $\kappa$，"
        r"则对任意 $\mu<\kappa$，该类窗口上的有害动作全部被接受，"
        "软惩罚的损害率因而存在一个不依赖于阈值选取的正下界，"
        r"要消除这一下界只能取 $\mu\ge\kappa$，而此时效用增益低于 $\mu$ 倍结构失真的编辑一并被拒绝。",
        r"证明。由判据，动作被接受当且仅当 $\Delta U(a)/D(x,a(x))>\mu$。"
        r"对该类窗口上的有害动作，该比值不低于 $\kappa$，故 $\mu<\kappa$ 时判据恒成立，"
        "这些动作全部进入接受集，其带来的损害不随参数调整而消失。"
        r"取 $\mu\ge\kappa$ 可以排除它们，代价是同一阈值同时排除了比值低于 $\mu$ 的全部编辑，"
        "其中包含有益的编辑。证毕。",
        "命题 1 的前提是效用信号与有害性在某类数据上同向增长，"
        "即抹平一段真实的极端波动同时得到高效用增益与大结构失真。"
        "本文的实验一正是刻画这一前提是否成立，因此命题的实际意义取决于该实验的结论，"
        "若反向区域很小则下界虽然存在但数值可忽略。"
        "合取条件没有这个下界，它的接受集由结构阈值直接切出，与效用增益的大小无关，"
        "无论某个动作的效用增益多高，结构失真超限即被拒绝。"
        "这一区别把两种做法的比较从是否使用副本这一实现细节，"
        "提升到结构约束应当以可交易还是不可交易的形式进入决策这一设计问题上。",
    ], template_idx=j)

    # 三 同类校准的生效条件
    rw("把两类证据直接相加，盲区会叠加起来",
       "把两类证据直接相加，盲区会叠加起来，因为它们的量纲和分布都不同。"
       r"CDP 的处理是先在画像空间中检索与当前窗口最相似的 $K$ 个邻居 $\mathcal{N}(x)$，"
       "相似度用画像向量经 L2 归一化后的余弦距离衡量，"
       "再用这组邻居的中位数与四分位距对行为签名做稳健标准化")

    k = find_paragraph(d, "检索到的邻居集合还有第二个用途")
    insert_after(d, k, [
        "同类校准的收益依赖于语料本身存在结构异质性，这一前提此前没有说明。"
        "若语料中所有窗口的复杂程度相近，则邻居的中位数与全语料的中位数几乎相同，"
        "两种标准化的结果也就几乎相同，同类校准退化为全局标准化。"
        "收益应当随语料的结构异质性单调增加，在同质语料上趋于零。"
        "这一点决定了检验它的语料必须跨越足够的结构跨度，"
        "本文因此在实验设计中同时使用工业与金融两类场景，"
        "并把异质性作为自变量单独扫描，具体安排见 4.2 节。"
        "弃权机制的情形与此类似，它在两类证据相互矛盾时拒绝处理，"
        "若语料中的窗口证据都很充分，弃权就没有触发的机会。",
    ], template_idx=k)

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"三点补强写入完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
