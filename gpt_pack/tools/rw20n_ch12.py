# -*- coding: utf-8 -*-
"""Chapters one and two in the same voice as the introduction.

The survey sections still opened by naming a category, and the preliminaries
still explained things the way a specification does rather than the way someone
would say them. The content stays, the sentences get shorter and the reasons get
stated in the order a reader would ask for them.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 1 章首
    rw("本文的工作与三个方向相关",
       "三个方向的工作与本文有关。时序数据清洗攒下了一批能直接调用的算子，"
       "时序数据质量评估给出了衡量一条数据值多少的办法，"
       "智能体的策略学习与安全约束则提供了在受限条件下改进决策的框架。"
       "前两个方向都在动手之前就把判断做完了，第三个方向的安全约束要靠专家事先写好，"
       "本文要做的是把这三样东西接成一个动手之后再判断、并且能从判断里学东西的闭环。")

    # 1.1
    rw("约束驱动是这一方向最成熟的思路",
       "这个方向上最成熟的想法是给数据划一条界。"
       "SCREEN[5]假定相邻两点之间的变化幅度有上下限，把越界的点拉回最近的合法取值，"
       "还给出了线性时间的在线算法。"
       "SpeedAcc[7]在速度之外又加了加速度约束，用二阶信息管住修复后的平滑程度。"
       "这两项处理的是单变量序列。"
       "MTCSC[8]把速度约束和聚类放在一起，借维度之间的相关性提高精度，"
       "MTSClean[15]则同时用行约束和列约束，能覆盖更多种错误形态。"
       "划界这条路好在讲得清楚、跑得也快，麻烦在于界从哪来。"
       "界来自领域知识，定得准不准直接决定修得好不好。")
    rw("另一条思路从统计模型出发",
       "另一条路让数据自己说话。"
       "IMR[6]指出检测异常和修复异常是两码事，"
       "把检测结果直接拿来当修复依据效果很差，"
       "于是改用自回归模型逐点估计再迭代收敛，"
       "同时拿少量已知正确的点当起始约束。"
       "这类方法对参数没那么敏感，代价是它要的那点种子信息在无标签场景里并不好找。")
    rw("近期出现了把算子编排交给强化学习的尝试",
       "近两年有人把算子的编排交给了强化学习[13]，"
       "用分层策略先判断是哪类问题再挑具体算子，"
       "奖励里加上平滑度和改动幅度两项来压住过度清洗。"
       "策略确实能从下游反馈里改进，"
       "可算子在训练途中就作用到原数据上了，探索时犯的错收不回来，"
       "安全性只在训练收敛之后的期望意义上成立，落到单个窗口上没有保证。")

    # 1.2
    rw("数据估值提供了另一种视角",
       "还有一类工作干脆不改数据，只算每条数据对模型有多大用处。"
       "Data Shapley[9]用合作博弈里的 Shapley 值刻画样本价值，理论上很完备，"
       "开销却随样本数涨得很快。"
       "Data-OOB[10]改用袋装模型的袋外估计把这笔开销压下来，"
       "KNNShapley[16]则靠近邻结构直接给出闭式解。"
       "这几项都是为独立同分布数据设计的，搬到时序上会把时间点之间的依赖丢掉。"
       "TimeInf[11]补了这一点，把影响函数定义在时间块上再聚合回单个时间点，"
       "既给出逐点分数又留住了时序结构。")
    rw("近期工作把大语言模型的先验引入质量判断",
       "也有工作把大模型的先验拉进来判断质量。"
       "TSRating[12]从趋势、频率、幅度和模式四个角度让大模型两两比较，"
       "再用元学习把这些判断蒸馏成一个轻量评分器，使评级能力能在不同领域之间迁移。"
       "该工作在十一个数据集上做了验证，只取评分最高的一半样本训练下游模型，"
       "效果就已经接近用全量数据训练。")
    rw("这一方向的产出始终是分数或排序",
       "这个方向交出来的东西始终是分数或者排序。"
       "它能指出哪些窗口有问题，说不了这些窗口该怎么处理，"
       "也没有环节去核对某次处理到底管不管用。"
       "而当低分窗口里混着稀有却正确的模式时，按分数丢弃会把它们一起丢掉。")

    # 1.3
    rw("在受约束条件下学习决策是强化学习的经典课题",
       "在约束下学决策是强化学习的老题目。"
       "受约束马尔可夫决策过程[17]把安全要求写成期望意义上的约束，"
       "用拉格朗日松弛和策略优化一起求解，"
       "它的保证在训练收敛之后成立，训练途中仍可能违反。"
       "屏蔽机制[14]走的是另一条路，在智能体和环境之间加一层过滤，"
       "动作只有不违反规约才放行，安全性因此每一步都成立，不用等收敛。"
       "屏蔽还把安全逻辑和策略优化拆开了，底下的学习算法可以随便换，这一点正合本文的需要。"
       "差别在于屏蔽的规约通常由领域专家写出来，"
       "而在数据治理里，一次编辑有没有害根本没法写成只关于这次编辑本身的条件，"
       "本文因此把规约换成了一个要等动作做完、测过之后才能判定的复合条件。")
    rw("在策略的具体形式上，本文的决策序列很短",
       "策略该做成什么样，取决于问题的规模。"
       "本文的决策序列很短，多数窗口一到三步就结束，"
       "状态经过特征提取之后维度不高，动作集合也就那么几个。"
       "这样的设定离上下文老虎机很近，离长程决策问题较远。"
       "上下文老虎机在线性收益假设下已经有成熟的上置信界算法和遗憾分析[18,19,20]，"
       "样本效率高，也容易解释清楚，本文因此选了这一族。")
    rw("统计侧的进展提供了标定屏蔽阈值的工具",
       "阈值该卡在哪，统计这边有现成的工具。"
       "共形风险控制[21]在可交换性假设下，"
       "为由阈值参数化的一族决策给出有限样本的风险上界，对数据分布不作任何假定。"
       "Learn Then Test[22]把这套思路推广到了更一般的风险函数。"
       "这两个框架都建立在同一个前提上，被约束的那个信号得是有害性的合理代理。"
       "本文面对的信号偏偏在一部分区域里与有害性反着走，"
       "所以不能只标定它，得先跟一个不依赖模型的条件合取起来再标定。")

    # 2.2
    rw("本文处理时序特征层面的噪声，按其产生机制分为随机与系统两类",
       "本文处理的是时序特征层面的噪声，按它怎么产生的分成两类，"
       "这一分法决定了它在多通道语料里留下的痕迹能不能相互印证。"
       "随机噪声来自环境扰动、设备误差和记录不一致，"
       "只作用在单个通道的一小段时间上，形态包括孤立尖峰、散点缺失、"
       "连续缺失片段和重复片段。"
       "它在通道之间彼此独立，所以某个通道上的异常，在同一时刻的其余通道里找不到对应。"
       "系统噪声来自采集设备的系统性偏差、数据来源切换和传感器漂移，"
       "它同时压在多个通道上，改变整段窗口的分布，"
       "形态包括水平位移、噪声放大和平台化。"
       "它在通道之间高度相关，同一时刻的多个通道会一起偏。")
    rw("两类噪声给治理带来的困难并不相同",
       "两类噪声带来的困难不一样。"
       "随机噪声在单个窗口上留下明显的局部痕迹，统计画像抓得住，"
       "难的是它和真实发生的极端事件在波形上几乎一模一样，"
       "光看单个通道分不出某个尖峰是故障还是事件。"
       "系统噪声改变整段分布，在模型行为上的表现又和合法的状态切换很像，"
       "水平位移和设备检修后的基线变化都会把预测误差抬上去，光看模型反馈同样分不出来。"
       "放到整个语料的尺度上还有一重麻烦。"
       "模型行为信号反映的是这个窗口对这个模型有多难预测，"
       "而难不难预测跟质量好不好并不是一回事，"
       "结构本来就复杂却完全干净的数据，同样会拿到很高的风险读数。"
       "这个偏差对按规则办事的方法只是一次误判，"
       "对会学习的方法就严重得多，因为策略会主动朝偏差的方向使劲，"
       "把降低预测难度当成目标去追。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"第 1 章与 2.2 完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
