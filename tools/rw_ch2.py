# -*- coding: utf-8 -*-
"""Rewrite chapter 2. Section 2.1's four sub headings are removed and their
bodies merged into continuous prose, so the symbols are defined in the narrative
rather than listed as entries."""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import (count_math, delete_paragraph, find_paragraph,
                          set_paragraph_md)

PATH = "docx/胡宏彬-进度文档-20260819.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)
    drop = []

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    def kill(prefix):
        drop.append(d.paragraphs[find_paragraph(d, prefix)])

    rw("本章先给出方法涉及的四个基础概念",
       "治理决策建立在四个基础概念之上。模型效用与时序结构保真度提供判据所需的两类读数，"
       "屏蔽提供施加判据的位置，共形风险控制提供确定阈值的方法。本章交代这四者，"
       "说明所处理的缺陷类型，再把治理问题形式化为屏蔽约束下的序贯决策。")

    # 2.1 去掉四个小节标题，正文并为连续叙述
    kill("2.1.1 冻结时序基础模型的行为探测")
    rw("冻结时序基础模型的行为探测指在不更新参数的前提下",
       "行为探测指在不更新参数的前提下，通过冻结模型对一个窗口的反应获取该窗口的证据。"
       r"记窗口为 $x$，冻结模型为 $f$，探测函数 $\mathrm{Probe}(f,x)$ 输出固定维度的行为签名 $b$，"
       "其分量覆盖逐位置预测误差的分位数、层间表示的余弦距离、遮挡恢复的稳定性、"
       "多视图预测的一致性、轻微扰动前后的输出变化，以及模型池内不同模型之间的分歧。"
       "只取预测误差是不够的，一段被尖峰污染的窗口和一段本就难以预测的窗口都会产生高误差，"
       "前者的误差集中在少数位置，后者的误差分布均匀，分位数信息能把两者分开。"
       "探测只做前向计算，不涉及梯度，单位开销远低于需要海森求逆的影响函数方法[11]，"
       "这在需要反复测量的强化学习设定下尤为重要。")
    kill("这样设计的原因是单一的预测误差不足以区分缺陷类型")

    kill("2.1.2 模型效用")
    rw("模型效用衡量一个窗口对目标模型的友好程度",
       "模型效用衡量一个窗口对目标模型的友好程度，本文把它定义为若干归一化误差分量的加权负和")
    rw("U(x) = − Σ_k w_k · g_k( Probe(f, x) )",
       r"$$U(x)=-\sum_{k}w_{k}g_{k}(\mathrm{Probe}(f,x))$$")
    rw("其中 g_k 是第 k 个误差分量",
       r"其中 $g_{k}$ 取自行为签名 $b$ 的第 $k$ 个误差分量，$w_{k}$ 为对应权重。"
       r"各分量都是越小越好，整体取负号后 $U$ 越大表示窗口对模型越友好。"
       r"一次候选动作 $a$ 带来的效用变化写作")
    rw("ΔU(a) = U(a(x)) − U(x)", r"$$\Delta U(a)=U(a(x))-U(x)$$")
    rw("这个差值只有在两次测量使用相同的留出跨度",
       r"该差值只有在两次测量使用相同的留出跨度和相同的归一化尺度时才有意义。"
       r"改变窗口长度的动作会破坏这一前提，因此同跨度同尺度是进入判据的硬性要求，"
       r"具体做法见 3.2 节。$\Delta U$ 既是本文奖励信号的来源，也是 2.2 节所述偏差的载体，"
       r"在使用它的同时避免被它误导是方法设计的核心。")

    kill("2.1.3 时序结构保真度")
    rw("时序结构保真度衡量一次编辑对序列固有结构的破坏程度",
       "时序结构保真度衡量一次编辑对序列固有结构的破坏程度，取值越低表示保持得越好。"
       "它只比较编辑前后的时序属性，与模型无关。参与比较的属性随算子的作用范围而不同，"
       "改动局限于有限位置的算子在其声明的足迹之外比较形状、极值、补片衔接、足迹大小与局部离散度，"
       "重写整条序列的算子则比较趋势、主周期、频谱能量分布、自相关结构、变点位置与极值。"
       r"记编辑前后的窗口为 $x$ 与 $a(x)$，第 $j$ 个属性上的归一化差异为 $d_{j}$，"
       r"对应权重为 $w_{j}$，结构失真定义为")
    rw("D(x, a(x)) = 0.7 · mean_j d_j + 0.3 · max_j d_j",
       r"$$D(x,a(x))=0.7\cdot\frac{\sum_{j}w_{j}d_{j}}{\sum_{j}w_{j}}+0.3\cdot\max_{j}d_{j}$$")
    rw("其中 d_j 是第 j 个属性上的归一化差异",
       "加权平均之外保留最差单项，可以避免某一项上的灾难性破坏被其余项平均掉。"
       "序列尾部被整体抹平就属于这种情形，它在多数属性上看起来变化不大，只在极值一项上暴露。"
       r"$D$ 与模型无关，因而能够独立于效用信号提供约束，在策略学习过程中也不会被策略操纵。")

    kill("2.1.4 屏蔽与共形风险控制")
    rw("屏蔽[14] 指在智能体与环境之间加入一层过滤器",
       "屏蔽[14]指在智能体与环境之间加入一层过滤器，动作生效之前先检查它是否违反给定规约，"
       "通过检查才被放行。屏蔽的两个基本要求是可靠性与非阻塞性，前者指违规动作不会被放行，"
       "后者指任意状态下至少存在一个可以放行的动作。屏蔽与策略学习解耦，底层算法可以自由选择，"
       "安全性在每一步都成立，不依赖训练收敛。")
    rw("共形风险控制[21] 在不假设数据分布的前提下",
       "共形风险控制[21]在不假设数据分布的前提下，为由阈值参数化的决策族提供有限样本的风险保证。"
       r"给定与部署数据可交换的校准集、有界的风险函数以及目标风险水平 $\alpha$，"
       r"该框架在嵌套阈值族 $\Lambda$ 上计算经验风险 $\hat{R}(\lambda)$，按"
       r"$\lambda^{\star}=\inf\{\lambda\in\Lambda:\hat{R}(\lambda)+\sqrt{\ln(1/\delta)/(2n)}\le\alpha\}$"
       r"选出阈值，其中 $n$ 为校准集大小，$\delta$ 为置信参数。"
       "风险关于阈值单调时可以避开多重比较校正带来的保守性，"
       "单调性不成立时退回逐阈值检验并做校正[22]。"
       "本文的风险函数取每个窗口上编辑是否造成损害的零一指示，"
       r"被标定的对象是屏蔽中的结构失真阈值 $\tau$。")

    # 2.2
    rw("本文处理时序特征层面的缺陷，按影响范围分为两类",
       "本文处理时序特征层面的缺陷，按影响范围分为两类。局部缺陷作用于窗口内有限的时间范围，"
       "包括孤立尖峰、散点缺失、连续缺失片段与重复片段，它们通常在序列上留下明显痕迹，"
       "统计画像对其检测能力较强。重复片段是其中的例外，被复制的片段本身在统计上完全正常，"
       "只有把它与上下文对照才能发现。全局缺陷改变整个窗口的分布，包括水平位移、噪声放大与平台化，"
       "影响不局限于某几个时间点。")
    rw("这两类缺陷给治理带来的困难体现在两个层面",
       "这两类缺陷带来的困难体现在两个层面。在单个窗口的尺度上，某些缺陷在模型行为上的表现"
       "与困难但正确的数据高度相似，水平位移与合法的状态切换都会抬高预测误差，"
       "仅凭模型反馈无法区分。在语料的尺度上，模型行为信号反映的是窗口对该模型的可预测程度，"
       "而窗口的可预测程度与它的质量并不等同，结构上本就复杂却完全干净的数据同样会得到高风险读数。"
       "这一偏差对基于规则的方法只是误判，对基于学习的方法则更严重，"
       "因为策略会主动朝着偏差的方向优化，把降低可预测难度当作目标去追求。")

    for p in drop:
        delete_paragraph(p)
    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"2.1 与 2.2 完成，删除 {len(drop)} 个小节标题，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
