"""Rewrite the abstract and introduction around a single line of argument.

The current text states the same observation five times, once in the opening,
once in the automation paragraph, twice in the family critique and once in the
figure caption, and restates the method three times, in the abstract, in the
introduction and in the contribution list. It also presents three challenges as
peers when the second and third only arise after the first has been answered in
a particular way.

The line kept here is that harm depends on the data being edited rather than on
the edit, so it cannot be judged before execution. Everything else follows from
deciding to judge afterwards on a sandbox copy.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import (count_math, delete_paragraph, find_paragraph,
                          insert_after, set_paragraph_md)

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)
    drop = []

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    def kill(prefix):
        drop.append(d.paragraphs[find_paragraph(d, prefix)])

    # 摘要，围绕一个决定重写
    rw("时序基础模型的能力上限越来越取决于训练语料的质量",
       "时序基础模型的能力上限越来越取决于训练语料的质量，而语料治理有一处特殊的困难，"
       "一次修改是否有害取决于被修改的那段数据，不取决于修改本身。"
       "同一个去尖峰算子作用在传感器故障上是修复，作用在真实发生的极端事件上是破坏，"
       "因此有害与否无法在动作执行之前判定。"
       "已有方法或者不动手只给样本打分，或者动手之后不再回头核对，都没有正面处理这一点。"
       "本文把判定推迟到执行之后，并把执行放在副本上，使判错的动作可以撤回。"
       "这一个决定引出两个必须解决的问题。"
       "事后判定需要依据，而能报告修改效果的只有目标模型，"
       "模型在被抹平的数据上给出的读数与有害性方向相反，单凭它会放行破坏性的修改，"
       "本文因此要求模型效用与时序结构两个相互独立的条件同时成立才允许提交，"
       "并用共形风险控制把结构条件的阈值标定到给定的损害率上。"
       "判定的结果同时是一次反馈，策略可以据此改进动作选择，"
       "而试错既然发生在副本上，学习过程本身就不修改语料。"
       "屏蔽因而承担双重职责，它拦下破坏性动作，也决定了哪些奖励能够到达策略。"
       "本文给出六条定理与一条命题及其证明，"
       "涵盖合取判定的损害单调性、非阻塞性、任意策略下的结构安全性、共形风险控制、"
       "标定间隔内保证退化的上界与屏蔽动作空间上的遗憾界，"
       "并说明把结构约束写成惩罚项时损害率存在不可消除的下界，在此基础上规划了九组实验。")

    # 引言第一段，把困难一次讲透
    rw("时序基础模型在大规模多来源语料上预训练",
       "时序基础模型在大规模多来源语料上预训练，再迁移到预测、分类与插补等下游任务[1-4]，"
       "模型结构趋于稳定之后，能力上限主要由训练语料的质量决定。"
       "真实语料中的缺失、噪声、尖峰与漂移会被模型当作规律学习，训练之前需要对语料做治理。"
       "治理的困难不在于找出这些异常，而在于判断找出来之后该不该动。"
       "以电力变压器监测语料为例，设备检修期间的一段水平漂移应当处理，"
       "它会让模型把异常水平当作正常基线，在随后的正常时段给出系统性偏高的预测。"
       "而一次真实发生的负荷突增在波形上与故障尖峰几乎一致，却是语料中最有价值的部分，"
       "抹掉它等于删去模型最需要学习的稀有模式。"
       "两者的区别不在算子也不在参数，同一个去尖峰算子带同样的参数施加下去，"
       "前者是修复后者是破坏，结果取决于那段数据里原本承载着什么。"
       "这决定了有害与否无法在动作执行之前判定。")

    # 删掉双重代价与重复的自动化段
    kill("这项工作的动机来自劣质数据的双重代价")
    kill("把治理做成自动化并不等于把清洗算子串起来")

    rw("已有工作沿两条路线展开",
       "面对这一困难，已有工作分两条路线，各自的处理方式与代价可以逐项说明。")

    # 两族评述合并为一段，紧扣主线
    rw("打分式选择的输出是一个标量",
       "两条路线在同一处停下。打分式选择不产生动作，因而不必判断某次修改是否有害，"
       "代价是面对一段含有尖峰的窗口只能整体丢弃，尖峰之外完好的部分一并舍去。"
       "修复式清洗补上了动作，却把判断放在了选择算子的那一刻，"
       "算子一旦选定就直接覆盖原值，此后没有任何机制核对这次改写是否达到预期。"
       "近期把算子编排交给强化学习的尝试让策略可以从反馈中改进，"
       "但算子在训练过程中立即生效，每一次错误探索都在真实语料上留下痕迹，"
       "面对拿不准的窗口也没有退回的选项。")
    kill("修复式清洗补上了动作这一环")

    # 本文的决定，以及它推出的两个问题
    rw("把这些缺口一并补上",
       "让判断发生在执行之后，就不再需要事先写出只关于算子与参数的安全规则，"
       "因为判断这时可以看到修改造成的实际后果。"
       "要让这样的判断有意义，执行必须可以撤回，否则判定为有害时已经无法挽回，"
       "本文因此把候选动作施加在工作副本的拷贝上，"
       "原副本只在判定通过时才被替换。"
       "这一个决定引出两个随之而来的问题。")
    rw("第一重挑战是安全规则无法事先写定",
       "第一个问题是判定依据从哪里来。"
       "修改是否有害只能从效果读出，而能报告效果的仪器只有目标模型。"
       "让模型的预测变准存在两条途径，修好缺陷是一条，"
       "把序列抹平使它更容易预测是另一条，后者同样会抬高效用读数。"
       "在需要保护的数据上，这两条途径给出的读数方向相反，"
       "单凭模型的意见去判定，恰恰会放行那些最该拦下的修改。"
       "本文因此在模型效用之外引入一个完全不看模型的结构条件，"
       "要求两者同时成立才允许提交，并把结构条件的阈值交给共形风险控制标定。")
    rw("第二重挑战是可用作奖励的信号本身带有偏差",
       "第二个问题是这些判定能不能被利用起来。"
       "每一次判定都记录了某个动作在某类窗口上的实际后果，这正是策略改进所需要的反馈。"
       "由于试错发生在副本上，未通过判定的尝试不留下任何痕迹，"
       "学习过程因而不以破坏语料为代价，这与算子立即生效的方案形成对照。"
       "把判定结果当作奖励还有一层作用，"
       "被撤销的动作只留下探测代价而拿不到正回报，"
       "策略据此学到的是能够通过结构检验的修复方式，"
       "而直接以模型效用为奖励会把策略引向抹平数据这条捷径。")
    kill("第三重挑战是试错的代价落在语料上")

    # 方法概述压缩，不再复述摘要
    rw("针对这三点，本文提出屏蔽强化学习驱动的时序数据治理智能体",
       "按照这一思路，本文提出屏蔽强化学习驱动的时序数据治理智能体 IntroAct-TS，"
       "把治理建模为带预算的受约束序贯决策。"
       "一次决策依次经过取证、试执行、判定与学习四个环节，"
       "分别由状态构建、沙箱重测、双信号屏蔽与策略优化四个模块承担，"
       "第 3 章逐一说明。图 1 用一对窗口说明判定要达到的效果。")

    d.save(PATH)
    for p in drop:
        delete_paragraph(p)
    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"摘要与引言重写完成，删除 {len(drop)} 段，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
