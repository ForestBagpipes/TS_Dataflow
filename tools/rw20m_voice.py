"""Say the same things in our own words.

The previous pass copied the reference paper down to its connectives, so the
opening announced a paradigm shift and the survey began with a phrase lifted
almost verbatim. What is worth keeping from that paper is the order in which
ideas arrive and the habit of letting each paragraph end where the next has to
begin. The wording should come from the material itself, which here means
starting from what people actually do with these models rather than from a
claim about the field.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 段一 从人们拿这些模型做什么讲起
    rw("人工智能领域正在经历一场重心转移",
       "风电场要预测明天的出力，变电站要排后天的负荷，交易台想提前知道波动会不会放大。"
       "这些事从前各做各的，模型、特征和调参经验都不共用。"
       "近两年的做法变了，先在海量时序上预训练一个基础模型，再对着具体任务微调，"
       "一套权重就能同时应付这几件事，"
       "在电力与金融场景下已经能追平甚至超过为单个任务专门训练的模型[1-4]。"
       "换来的结果是差距从架构挪到了数据上，各家的网络结构正在趋同，"
       "剩下的高低主要看预训练时喂进去的是什么。"
       "时序语料好不好用可以从两处看。"
       "一处是模态齐不齐，设备有平稳运转的时候，也有启停切换和故障前兆的时候，"
       "市场有波澜不惊的月份，也有剧烈震荡的那几天，"
       "模型训练时没见过某一类形态，上线之后多半也认不出来。"
       "另一处是杂音多不多，传感器会漂移，通信会丢包，人工录入会填错，"
       "这些痕迹留在语料里就会被当成规律学走。"
       "实际采到的数据在这两处都靠不住，而监测点位和交易品种还在增加，"
       "语料的体量涨得比人能审核的速度快得多。"
       "怎么从一大批含杂音的时序记录里整理出可用的语料，"
       "成了训练时序基础模型绕不开的一环。")

    # 段二 这批方法叫什么，做什么
    rw("为应对这一需要，时序数据治理作为高质量数据准备的重要分支",
       "围绕这件事已经积累了一批方法，通称数据治理[5,6]。"
       "它们要回答的是哪些地方有问题，以及问题该怎么办。"
       "有的按事先定好的规则去改可疑的读数，有的给每条数据估一个价值再决定留不留。"
       "这类方法把整备的规模从人工能承受的几千条推到了十万量级，"
       "也让同一批数据在不同轮次里得到一致的处理。")

    # 段三 时序数据特有的麻烦
    rw("然而，时序数据的一个特点让治理变得远比通用数据困难",
       "放到时序数据上，治理有一处别处没有的麻烦。"
       "一次改动是好是坏，多数时候不由改法决定，由被改的那一段决定。"
       "拿变压器的监测记录来说，检修期间读数会整体抬高一截，这一段该压回去，"
       "不然模型会把抬高后的水平当成常态，检修结束很久之后给出的预测还偏着。"
       "可另一种情形看上去几乎一样，某天负荷突然冲高，"
       "波形与故障造成的尖峰难以分辨，它却是语料里最值钱的部分，"
       "削掉等于把模型最该学的那类形态删了。"
       "两次面对的是同一个去尖峰算子和同一组参数，一次是修好，一次是毁掉，"
       "分野只在那段数据本身承载着什么。"
       "这就意味着，靠事先写死的规则去决定某次改动值不值得做，从道理上就靠不住。")

    # 段四 梳理的切入角度
    rw("为系统评估现有方法在这一问题上的适用性",
       "已有做法可以按两件事归类，判断发生在什么时候，以及判断依据什么。"
       "表 1 按这两点分成三类。")

    # 段五到七 三条路线，措辞自然化
    rw("（1）修复式清洗依靠先验约束判定取值是否合法",
       "（1）修复式清洗看取值是否越过了事先给定的界。"
       "SCREEN[5]假定相邻两点之间的变化幅度有上下限，把越界的点拉回最近的合法取值，"
       "IMR[6]换成自回归模型逐点估计再迭代收敛，"
       "MTCSC[8]把速度约束和聚类放在一起，借维度之间的相关性提高精度。"
       "这一类的判断在选定算子那一刻就结束了，规则给出结果，改写随即落到原值上。")
    rw("（2）打分式选择依据样本对模型的估计贡献判定去留",
       "（2）打分式选择看这条数据对模型有多大用处。"
       "Data Shapley[9]用合作博弈里的 Shapley 值算每个样本的价值，"
       "Data-OOB[10]改用袋外估计把这笔开销压下来，"
       "TimeInf[11]把影响函数放到时间块上以保住时序结构，"
       "TSRating[12]则让大模型两两比较再蒸馏出一个轻量评分器。"
       "这一类给出的是分数和排序，语料按分数取舍，本身不被改动。")
    rw("（3）学习式编排依据下游反馈的期望回报判定该调用哪个算子",
       "（3）学习式编排看哪个算子在下游能换来更高的回报。"
       "清洗智能体[13]用分层策略决定在什么窗口上做什么操作，"
       "把下游误差的变化当成奖励，策略会随训练慢慢变好。"
       "这一类把判断交给学到的价值估计，而算子在训练途中就已经生效。")

    # 段八 局限总起
    rw("经考察，这些方法在各自设定下都能取得不错的效果",
       "这三类在各自的设定里都能跑出不错的结果。"
       "回到上面那处麻烦，它们共同露出两块短板。")

    # 段九 局限一
    rw("1）判定时刻早于执行时刻，选错之后无法挽回",
       "1）判断落在动作之前，做错了退不回来。"
       "修复式清洗在规则给出结论的同时就把改写压到了原值上，"
       "此后没有任何环节回头核对这次改写有没有达到预期，"
       "SCREEN[5]和 MTCSC[8]都是这样，速度约束一旦判定某点越界，替换立刻发生。"
       "学习式编排让策略能从反馈里改进，"
       "可清洗智能体[13]的算子同样在训练途中生效，"
       "每一次探索失误都实实在在落在语料上，策略学得越久语料伤得越多。"
       "打分式选择躲开了这个问题，代价是它根本不动手，"
       "遇到一段只在局部有尖峰的窗口，"
       "Data Shapley[9]和 TimeInf[11]这类方法只能整窗丢掉，尖峰之外完好的部分一并搭进去。"
       "三条路子因此卡在同一个地方，动手的没有退路，有退路的不动手。")

    # 段十 局限二
    rw("2）判定所依据的信息单一，而在需要保护的数据上这一信息会给出相反的读数",
       "2）判断只靠一路信息，而这路信息在最该谨慎的地方会给出反向的读数。"
       "修复式清洗只问取值有没有越界，"
       "而一次真实的极端事件在数值上同样越界，界本身分不开这两种情形。"
       "打分式选择和学习式编排最终都看模型的表现，"
       "问题在于让模型预测得更准有两条路，把缺陷修好是一条，"
       "把序列削平使它更好预测是另一条，后者照样能让误差降下来。"
       "在稀有事件所在的那些窗口上，这两条路给出的读数正好相反，"
       "只听模型的意见去判断，放行的恰恰是最该拦住的那些改动。")

    # 段十一 挑战
    rw("针对上述局限，当前需要一种能够在动作执行之后判定",
       "要补上这两块短板，判断得挪到动作做完之后，而且做错了能退回去。"
       "真按这个路子走，有两道坎。"
       "头一道在依据上。改动是好是坏只能从效果读出来，"
       "而能报告效果的仪器只有目标模型，上面第二块短板说的正是这台仪器在关键处不可信。"
       "所以判断不能只问它，还得有一路不依赖模型的证据来对质，"
       "麻烦的是这路证据该卡在哪个数值上，没人能凭经验事先定下来。"
       "第二道在代价上。让策略从判断结果里学东西需要反复试，"
       "而语料和游戏或者仿真环境不一样，它没有可以重开的存档，被削平的峰值找不回来。"
       "怎么让学习攒够经验的同时不在攒的过程中把语料弄坏，"
       "是把判断后移之后必须一并解决的事。")

    # 段十二 方法
    rw("为解决判定依据存在偏差与试错代价不可恢复这两个问题",
       "IntroAct-TS 按这个路子搭建，把治理写成带预算的受约束序贯决策。"
       "它先从窗口自身的统计画像和冻结基础模型的行为反应里取证，"
       "并拿画像相近的邻居作参照做稳健标准化，让不同窗口的读数能放在一起比。"
       "接着把候选动作施加到工作副本的拷贝上试着执行一次再重新测量，原值在这期间不动，"
       "这样每次尝试都有确切的后果可读，而尝试本身不留痕迹。"
       "对着头一道坎，判定要求模型效用改善和时序结构受控两件事同时成立才放行，"
       "其中结构那一条完全不看模型的意见，"
       "它的阈值交给共形风险控制去标定，把该卡在哪里这件事从经验判断变成了统计问题。"
       "对着第二道坎，所有候选都在副本上执行且提交要过判定，"
       "没通过的尝试不改动任何数据，学习因此不必拿语料去换。"
       "每次判定的结果最后回流成策略的奖励，"
       "被撤销的动作只留下探测开销而拿不到正回报，"
       "策略据此更新动作价值估计，并在窗口之间安排探测预算，"
       "使治理在结构复杂又含杂音的时序语料上更可靠也更省。"
       "图 1 用一对波形相近的窗口说明这一过程怎么给出相反的裁决。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"引言换成自己的话，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
