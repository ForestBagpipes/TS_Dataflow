"""Chapter 3, sections 3.1 to 3.3."""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import (count_math, find_paragraph, insert_after,
                          set_paragraph_md)

PATH = "docx/胡宏彬-进度文档-20260819.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    rw("本章介绍 IntroAct-TS 方法的具体实现",
       "本章给出四个模块的具体实现与相应的理论性质。"
       "状态构建负责取证，沙箱重测负责把动作的后果测出来，"
       "双信号屏蔽负责裁决并给出安全保证，策略优化负责从裁决中学习并分配预算，"
       "最后分析各模块与整体的时间复杂度。")

    # 3.1 CDP
    rw("为应对缺少质量标签下证据不足的挑战",
       "缺少质量标签时单一证据存在盲区，CDP 因而从两个来源取证，"
       "它们的失效区域并不重合，这是把两类证据同时保留的原因。")
    rw("第一类证据是统计画像",
       r"第一类证据是统计画像 $p\in\mathbb{R}^{12}$，从窗口自身提取，"
       "覆盖缺失率、异常密度、趋势强度、季节强度、频谱特征、平稳性、变点数量与复杂度，"
       "其中变点数量由线性代价的变点检测算法给出[27]。"
       "这类属性对留下局部痕迹的缺陷敏感，尖峰会抬高异常密度，缺失片段会抬高缺失率。"
       "它的盲区在于统计上正常的缺陷，重复片段就属于此类，"
       "被复制的片段与原片段具有完全相同的统计属性。")
    rw("第二类证据是冻结基础模型的行为签名",
       r"第二类证据是冻结基础模型的行为签名 $b$，反映模型处理这个窗口时的困难程度。"
       "重复片段虽然统计正常，却会让模型在遇到第二次出现时给出异常自信的预测，"
       "这种反常在行为签名上留下痕迹。行为证据的盲区在于它无法区分数据有问题和数据本身复杂，"
       "两者都会让模型表现变差。")

    idx = find_paragraph(d, "把两类证据直接相加会让盲区叠加")
    set_paragraph_md(d.paragraphs[idx],
       "把两类证据直接相加会让盲区叠加而非抵消，因为它们的量纲和分布都不同。"
       r"CDP 的处理是先在画像空间中检索与当前窗口最相似的 $K$ 个邻居 $\mathcal{N}(x)$，"
       "相似度用画像向量经 L2 归一化后的余弦距离衡量，"
       "再用这组邻居的中位数与四分位距对行为签名做稳健标准化")
    insert_after(d, idx, [
        r"$$z=\frac{b-\mathrm{med}\{b_{i}:i\in\mathcal{N}(x)\}}"
        r"{\mathrm{IQR}\{b_{i}:i\in\mathcal{N}(x)\}+\epsilon}$$",
        r"其中 $\epsilon$ 为防止除零的小量。经过这一步，一个波动本就剧烈的窗口不会仅仅因为难以预测"
        r"就被判为低质，因为与它比较的邻居同样波动剧烈。"
        r"标准化后的行为分量按权重聚合为行为风险 $r_{\mathrm{behav}}=z^{\top}w$，"
        r"与统计画像给出的 $r_{\mathrm{stat}}$ 一同送入缺陷类型的后验估计，"
        r"三者与画像、签名共同构成状态 $s$。",
    ], template_idx=idx)

    rw("这里检索到的邻居集合还有第二个用途",
       r"检索到的邻居集合还有第二个用途。同一组邻居定义了一个画像簇 $j$，"
       "SPO 的动作价值估计正是按簇维护的，因为同一簇内的窗口在结构上相似，"
       "某个算子在其中一个窗口上有效往往意味着在其余窗口上也有效。"
       "CDP 因此既提供状态，也提供策略泛化所依赖的划分。算法 1 给出完整流程。")

    # 3.2 SIR
    rw("CDP 给出的状态说明了窗口可能存在什么问题",
       "CDP 给出的状态说明了窗口可能存在什么问题，却没有回答某个具体动作施加下去会发生什么。"
       "回答这个问题需要真正执行一次动作并观察结果。"
       "强化学习的设定给这件事加了一层要求，学习需要反复尝试，而语料被修改之后无法还原。"
       "SIR 把执行与提交分开，同时满足这两方面的需要。")
    rw("候选动作作用在工作副本的拷贝上",
       r"候选动作作用在工作副本的拷贝上，得到候选窗口 $c=a(x')$，原副本 $x'$ 保持不变。"
       r"随后用与事前完全相同的探测函数测量 $c$，得到 $U(c)$，"
       r"与 $U(x')$ 相减即为该动作的效用变化。这一读数有两个去向，"
       "一是进入 CDS 作为裁决依据，二是在裁决之后成为策略更新所用的奖励。"
       "两个用途都要求读数在不同窗口与不同轮次之间可比，下面的引理给出了具体条件。")
    rw("引理 1（可比性条件）",
       r"引理 1（可比性条件）若两次效用测量使用相同的留出跨度与相同的归一化尺度 $\sigma$，"
       r"且 $\sigma$ 在动作执行前确定并在整个决策过程中固定，"
       r"则 $\Delta U$ 的符号只反映模型表现的变化，不受动作引起的量纲改变影响。")
    rw("证明。设归一化尺度为 σ",
       r"证明。设归一化尺度为 $\sigma$，事前误差分量为 $g_{k}(x)/\sigma$，事后为 $g_{k}(c)/\sigma$。"
       r"由于 $\sigma$ 在两次测量中取同一常数，"
       r"$\Delta U=-\sum_{k}w_{k}(g_{k}(c)-g_{k}(x))/\sigma$ 的符号由未归一化的误差差值决定，"
       r"与 $\sigma$ 的具体取值无关。若 $\sigma$ 随窗口内容重新估计，则事前事后取不同值，"
       "差值中会混入尺度变化项，符号不再可解释。同理，若留出跨度在动作后发生改变，"
       "两次测量作用于不同的时间区间，差值失去意义。证毕。")
    rw("引理 1 对 SIR 的实现提出了两条约束",
       "引理 1 对 SIR 的实现提出两条约束。归一化尺度取分块四分位距的中位数并在决策开始时固定，"
       "这样即使窗口中存在整段水平位移，尺度也不会被这段位移撑大。"
       "改变窗口长度的动作在共有的重叠区间上比较，避免留出跨度发生变化。"
       r"满足这两条之后，同一个 $\Delta U$ 才能既支撑裁决又支撑学习。")
    rw("SIR 还负责把裁决结果转换为奖励",
       "SIR 还负责把裁决结果转换为奖励。被接受的动作以其效用增益计入正奖励，"
       "被撤销的动作只计入探测代价形成负奖励，保留与拒绝处理的奖励为零。"
       "这样的设计使策略在提出动作时同时考虑两件事，动作能带来多少改善，"
       "以及这个动作有多大可能通过屏蔽。3.3 节将说明，"
       "正是后一项使策略避开了以抹平换取效用的捷径。")

    # 3.3 CDS
    rw("SIR 给出了效用变化，但正如 2.2 节所述",
       "SIR 给出了效用变化，而 2.2 节已经说明效用信号在部分数据上与有害性方向相反。"
       r"仅凭 $\Delta U$ 作出裁决会放行那些通过抹平序列换取低误差的动作。"
       "在策略需要学习的设定下后果比误判更严重，因为策略会朝着这个方向持续优化。"
       "CDS 的做法是要求两类相互独立的证据同时支持这次提交。")

    idx = find_paragraph(d, "CDS 的判据由三个条件合取而成")
    set_paragraph_md(d.paragraphs[idx], "CDS 的判据由三个条件合取而成")
    insert_after(d, idx, [
        r"$$\mathrm{Accept}(a)=\mathbb{1}\big[\Delta U(a)>\varepsilon\ \wedge\ "
        r"D(x,a(x))<\tau\ \wedge\ R(a)<\eta\big]$$",
        r"效用条件 $\Delta U(a)>\varepsilon$ 回答改完之后目标模型是否真的更好，"
        "它使用模型反馈，能够捕捉统计规则观察不到的改善。"
        r"结构条件 $D(x,a(x))<\tau$ 回答这次改动是否破坏了序列固有的结构，"
        "它完全不看模型意见，因此可以拦下抹平类动作。"
        r"风险条件 $R(a)<\eta$ 回答当前证据是否足以支持这次决策，在证据薄弱时阻止强行处理。"
        "三者同时满足才提交，任一不满足即撤销。",
    ], template_idx=idx)

    rw("定理 1（合取屏蔽的损害单调性）",
       r"定理 1（合取屏蔽的损害单调性）设 $A_{U}$ 与 $A_{D}$ 分别是仅施加效用条件"
       r"与仅施加结构条件时的接受集，$A=A_{U}\cap A_{D}$ 是复合屏蔽的接受集。"
       r"记 $H(\cdot)$ 为接受集中造成损害的编辑数量，"
       r"则 $H(A)\le\min\{H(A_{U}),H(A_{D})\}$。")
    rw("证明。由判据定义，A 是 A_U 与 A_D 的交集",
       r"证明。由判据定义，$A$ 是 $A_{U}$ 与 $A_{D}$ 的交集，故 $A\subseteq A_{U}$ 且 $A\subseteq A_{D}$。"
       r"损害数量 $H$ 是接受集上的计数，对集合包含关系单调不减，"
       r"因此 $H(A)\le H(A_{U})$ 且 $H(A)\le H(A_{D})$，取二者较小值即得结论。证毕。")
    rw("定理 1 不依赖任何一个条件的判别力",
       "定理 1 不依赖任何一个条件的判别力。即使效用条件在某类数据上完全失效，"
       "复合屏蔽造成的损害也不会超过仅用结构条件的情形。"
       "该结论针对损害总量，接受集缩小的同时修复收益也会减少，"
       "两者的权衡由 3.4 节末尾的阈值标定处理。")

    rw("屏蔽在本方法中的第二重作用来自它与奖励的耦合",
       "屏蔽的第二重作用来自它与奖励的耦合。由 3.2 节的奖励定义，"
       "只有通过屏蔽的动作才计入正奖励，被撤销的动作只留下探测代价。"
       r"策略实际收到的回报因而是经过结构条件过滤后的 $\Delta U$ 而非原始读数。"
       "一个抹平动作即使拿到很高的效用读数，也会因结构失真超限而被撤销，最终计入负奖励。"
       "策略在若干轮之后会学到，在需要保护的窗口上提出抹平动作是不划算的，"
       r"从而在提议阶段就避开这类动作。若把奖励换成未经过滤的 $\Delta U$，"
       "同样的学习过程会得到相反的结果。这一对比构成了 4.2 节奖励塑形消融实验的设计依据。")

    rw("裁决之后的控制流有五个去向",
       "裁决之后的控制流有五个去向。三条件同时满足时接受动作，"
       "把候选副本提交为新的工作副本并记录轨迹。效用未改善或结构失真超限时撤销，"
       "恢复原副本，并把撤销原因写入状态。仍有可信候选且预算未耗尽时可以尝试其他动作，"
       "此时策略能够依据撤销原因调整方向，被结构条件否决意味着应当换用改动足迹更小的算子，"
       "被效用条件否决则意味着缺陷类型的判断可能有误。"
       "窗口风险高但无法可靠修复时转入隔离，证据不足或预算耗尽时拒绝处理并结束该窗口。"
       "算法 2 给出完整流程。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"3.1 至 3.3 前半完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
