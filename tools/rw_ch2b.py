# -*- coding: utf-8 -*-
"""Chapter 2, sections 2.3 and 2.4. Adds the decision risk formula, which the
previous draft named but never defined, matching verify.action_risk."""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import (count_math, delete_paragraph, find_paragraph,
                          insert_after, set_paragraph_md)

PATH = "docx/胡宏彬-进度文档-20260819.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    rw("给定含缺陷的时序语料 D",
       r"给定含缺陷的时序语料 $\mathcal{D}$，其中每个窗口 $x$ 是长度固定的单通道序列，"
       r"给定动作空间 $\mathcal{A}$ 与总探测预算 $B$，治理的目标是学习策略 $\pi$，"
       "为每个窗口选择动作序列，在提高语料对目标模型效用的同时不破坏窗口原有的时序结构，"
       "并在证据不足时不做处理。把治理过程建模为受约束的马尔可夫决策过程[17]，五个要素定义如下。")

    rw("状态 s 由窗口的统计画像、行为签名",
       r"状态 $s$ 由窗口的统计画像、行为签名、校准后的风险分量、缺陷类型后验，"
       r"以及该窗口内已尝试动作的历史与剩余预算构成。动作 $a$ 取自 $\mathcal{A}$，"
       "包含保留、插补、去尖峰、去噪、重分段、隔离与拒绝处理七类及其参数。"
       "转移由沙箱执行与重测给出，动作作用于工作副本的拷贝，重测产生新的效用读数，"
       "状态随之更新。奖励定义为")
    rw("r(s, a) = ΔU(a) · 1[Accept(a)] − c · Cost(a) · 1[¬Accept(a)]",
       r"$$r(s,a)=\Delta U(a)\cdot\mathbb{1}[\mathrm{Accept}(a)]"
       r"-c_{0}\cdot\mathrm{Cost}(a)\cdot\mathbb{1}[\neg\mathrm{Accept}(a)]$$")
    rw("其中 Accept 是屏蔽的裁决",
       r"其中 $\mathrm{Accept}(a)$ 是屏蔽的裁决，$\mathrm{Cost}(a)$ 是该动作消耗的探测次数，"
       r"$c_{0}$ 是探测代价的折算系数。约束为")
    rw("D(x, a(x)) ≤ τ ,  R(a) ≤ η ,  Σ Cost(a) ≤ B",
       r"$$D(x,a(x))\le\tau,\qquad R(a)\le\eta,\qquad\sum_{a}\mathrm{Cost}(a)\le B$$")

    # 决策风险此前只有名称没有定义，此处补齐，与实现一致
    idx = find_paragraph(d, "其中 R(a) 表示决策风险")
    set_paragraph_md(d.paragraphs[idx],
       r"其中 $R(a)$ 为决策风险，度量当前证据支持该动作的充分程度，由三项加权而成")
    insert_after(d, idx, [
        r"$$R(a)=\mathrm{clip}\big(0.45(1-\mathrm{depth})+0.25\,\mathrm{cost}"
        r"+0.30(1-\mathrm{cons}),\,0,\,1\big)$$",
        r"式中 $\mathrm{depth}$ 为行为证据改善的深度，$\mathrm{cons}$ 为改善在各行为分量上的一致性，"
        r"$\mathrm{cost}$ 为算子的归一化代价，三者都取自本次候选自身而非窗口的缺陷假设。"
        r"用假设的后验充当风险曾是早期做法，实测显示它与编辑是否成功反向，"
        r"后验最确信的十分之一窗口反而更容易收到错误编辑，因此改用上式的三项。"
        r"$R(a)$ 越小表示提交越安全。上式定义在单个窗口上，"
        "而治理的最终对象是整个语料，两者通过下面的损害定义连接。",
    ], template_idx=idx)

    rw("定义 1（编辑损害）",
       r"定义 1（编辑损害）设窗口 $x$ 的干净参考为 $x^{\circ}$，一次被提交的编辑把 $x$ 变为 $a(x)$。"
       r"若 $\mathrm{dist}(a(x),x^{\circ})>\mathrm{dist}(x,x^{\circ})$，"
       "即编辑后的窗口比编辑前更远离干净参考，则称该编辑造成损害，"
       r"记指示量 $h(a,x)=1$，否则 $h(a,x)=0$。"
       r"语料层面的损害率定义为被提交编辑中 $h$ 取值为 1 的比例。")

    rw("对于本就干净的窗口，其干净参考即自身",
       "对于本就干净的窗口，其干净参考即自身，任何非平凡的编辑都会造成损害，"
       "这与保护稀有模式的目标一致。干净参考只在评测与标定阶段可得，治理过程本身不使用它。")

    rw("（1）奖励信号与约束建立在不同来源的证据上",
       r"（1）奖励信号与约束建立在不同来源的证据上，且奖励信号本身可被策略利用。"
       r"$\Delta U$ 来自冻结模型的行为反馈，$D$ 来自序列自身的统计属性。"
       r"若直接以 $\Delta U$ 为奖励做策略优化，策略会发现抹平序列能稳定获得高回报，"
       "从而系统性地选择破坏性动作。约束因此不能只作为安全兜底，"
       "还必须参与塑造策略实际收到的奖励。")

    rw("（3）问题是带预算的序贯决策",
       "（3）问题是带预算的序贯决策。每次动作执行后状态发生变化，"
       "后续动作依赖前序结果与被否决的原因，而探测次数在语料范围内受总量限制，"
       "因此需要同时决定窗口内的动作顺序与窗口之间的预算分配。")

    # 2.4
    rw("考虑到上述三个特征，我们提出了 IntroAct-TS 方法",
       "针对上述三个特征，本文提出 IntroAct-TS 方法，整体框架如图 2 所示。"
       "该方法按状态取证、沙箱试执行、屏蔽裁决、反馈学习的顺序完成语料治理，"
       "把一个无法事先判定的问题转化为一系列可以事后核验并从中学习的单步决策。")

    rw("拿到可比的读数之后，我们设计了基于共形标定的双信号屏蔽算法",
       "拿到可比的读数之后，基于共形标定的双信号屏蔽算法（CDS）负责裁决。"
       "它要求模型效用改善、结构失真受控与决策风险有界三者同时成立才允许提交，"
       "任一不满足即撤销候选并保留原副本。其中结构条件不依赖模型意见，"
       "因此能够拦下通过抹平序列换取低误差的动作。"
       r"CDS 中的结构阈值 $\tau$ 由共形风险控制标定，使提交编辑的损害率获得有限样本的保证。"
       "CDS 的作用不止于安全兜底，由于奖励只在动作被接受时才计入正值，"
       "被撤销的动作只带来探测代价，屏蔽实际上决定了哪些回报能够到达策略，"
       "因而同时充当奖励塑形器。")

    rw("最后，为让策略从裁决中改进",
       "为让策略从裁决中改进并把探测预算用在更需要的地方，"
       "基于屏蔽反馈的策略优化与预算分配算法（SPO）以 CDS 的裁决与奖励更新动作价值估计，"
       "用上置信界在探索与利用之间取舍，并依据价值估计在窗口之间分配探测次数，"
       "把预算集中到证据模糊而潜在收益较大的窗口上。"
       "SPO 的输出回流为下一轮 CDP 的上下文，使状态取证、试执行、裁决与学习形成闭环。"
       "整个过程的动作、参数、读数与裁决都写入治理轨迹，既支撑事后追溯，"
       "也构成策略更新所依据的经验。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"2.3 与 2.4 完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
