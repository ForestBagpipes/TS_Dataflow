# -*- coding: utf-8 -*-
"""Final language pass, modelled on how the reference paper moves between ideas.

The pattern there is that each step is driven by a difficulty the previous step
leaves open, so the connective is a reason rather than an ordinal. A concept is
introduced by saying what it has to measure, then formalised, then read back in
words, then placed in the argument. This pass applies that shape where the
current text still announces its structure instead of following it.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 第 2 章章首与 2.1 的过渡
    rw("治理决策建立在四个基础概念之上",
       "一次编辑是否值得提交，取决于它在两个方向上的表现，"
       "模型是否因此变得更容易处理这段数据，以及序列自身的结构是否被保住。"
       "这两个方向需要各自的度量，而度量之后还需要一个位置来施加判断，"
       "以及一种方法来确定判断的阈值。本章依次交代这四者，"
       "说明所处理的噪声类型，再把治理问题形式化为屏蔽约束下的序贯决策。")

    rw("行为探测指在不更新参数的前提下",
       "衡量模型是否变得更容易处理一段数据，需要一个能从模型读出证据的手段。"
       "行为探测指在不更新参数的前提下，通过冻结模型对一个窗口的反应获取该窗口的证据。"
       r"记窗口为 $x$，冻结模型为 $f$，探测函数 $\mathrm{Probe}(f,x)$ 输出固定维度的行为签名 $b$，"
       "其分量覆盖逐位置预测误差的分位数、层间表示的余弦距离、遮挡恢复的稳定性、"
       "多视图预测的一致性、轻微扰动前后的输出变化，以及模型池内不同模型之间的分歧。"
       "签名之所以不能只取预测误差，是因为一段被噪声污染的窗口和一段本就难以预测的窗口"
       "都会产生高误差，前者的误差集中在少数位置，后者的误差分布均匀，"
       "分位数信息能把两者分开。"
       "探测只做前向计算，不涉及梯度，单位开销远低于需要海森求逆的影响函数方法[11]，"
       "这在需要反复测量的强化学习设定下决定了方法是否可行。")

    rw("模型效用衡量一个窗口对目标模型的友好程度",
       "有了行为签名，模型侧的度量可以定义出来。"
       "模型效用衡量一个窗口对目标模型的友好程度，取若干归一化误差分量的加权负和")

    rw("时序结构保真度衡量一次编辑对序列固有结构的破坏程度",
       "效用只回答了模型是否更容易处理这段数据，"
       "一个把序列抹平的动作同样能让模型更容易处理它，因此还需要一个与模型无关的度量。"
       "时序结构保真度衡量一次编辑对序列固有结构的破坏程度，取值越低表示保持得越好，"
       "它只比较编辑前后的时序属性。"
       "参与比较的属性随算子的作用范围而不同，"
       "改动局限于有限位置的算子在其声明的足迹之外比较形状、极值、补片衔接、足迹大小与局部离散度，"
       "重写整条序列的算子则比较趋势、主周期、频谱能量分布、自相关结构、变点位置与极值。"
       r"记编辑前后的窗口为 $x$ 与 $a(x)$，第 $j$ 个属性上的归一化差异为 $d_{j}$，"
       r"对应权重为 $w_{j}$，结构失真定义为")

    rw("屏蔽[14]指在智能体与环境之间加入一层过滤器",
       "两个度量都有了，还需要确定它们在哪里被施加。"
       "屏蔽[14]指在智能体与环境之间加入一层过滤器，动作生效之前先检查它是否违反给定规约，"
       "通过检查才被放行。屏蔽的两个基本要求是可靠性与非阻塞性，"
       "前者指违规动作不会被放行，后者指任意状态下至少存在一个可以放行的动作。"
       "屏蔽与策略学习解耦，底层算法可以自由选择，"
       "安全性在每一步都成立，不依赖训练收敛。")

    rw("共形风险控制[21]在不假设数据分布的前提下",
       "屏蔽给出了施加判断的位置，判断所用的阈值还需要一种确定方式，"
       "而在无标签场景中这个阈值无法由领域知识给定。"
       "共形风险控制[21]在不假设数据分布的前提下，"
       "为由阈值参数化的决策族提供有限样本的风险保证。"
       r"给定与部署数据可交换的校准集、有界的风险函数以及目标风险水平 $\alpha$，"
       r"该框架在嵌套阈值族 $\Lambda$ 上计算经验风险 $\hat{R}(\lambda)$，按"
       r"$\lambda^{\star}=\inf\{\lambda\in\Lambda:\hat{R}(\lambda)+\sqrt{\ln(1/\delta)/(2n)}\le\alpha\}$"
       r"选出阈值，其中 $n$ 为校准集大小，$\delta$ 为置信参数。"
       "风险关于阈值单调时可以避开多重比较校正带来的保守性，"
       "单调性不成立时退回逐阈值检验并做校正[22]。"
       "本文的风险函数取每个窗口上编辑是否造成损害的零一指示，"
       r"被标定的对象是屏蔽中的结构失真阈值 $\tau$。")

    # 第 3 章章首
    rw("本章给出四个模块的具体实现与相应的理论性质",
       "上一章把治理问题写成了带预算的受约束序贯决策，"
       "余下的是如何在无标签条件下取得决策所需的证据、如何在不破坏数据的前提下测出动作的后果、"
       "如何判定一次改动可以提交，以及如何让判定的结果反过来改进后续的选择。"
       "本章按这四个环节给出具体实现与相应的理论性质，最后分析时间复杂度。")

    # 3.2 SIR 的过渡
    rw("CDP 给出的状态说明了窗口可能存在什么问题",
       "状态说明了窗口可能存在什么问题，却没有回答某个具体动作施加下去会发生什么。"
       "这个问题只能通过真正执行一次动作并观察结果来回答，"
       "而强化学习需要反复尝试，语料一旦被修改就无法还原，"
       "两个要求直接冲突。SIR 把执行与提交分开，使两者可以同时满足。")

    # 3.3 CDS 的过渡
    rw("SIR 给出了效用变化，而 2.2 节已经说明效用信号在部分数据上与有害性方向相反",
       "SIR 给出了可比的效用读数，但 2.2 节已经指出这个信号在部分数据上与有害性方向相反。"
       r"仅凭 $\Delta U$ 作出裁决会放行那些通过抹平序列换取低误差的动作，"
       "而在策略需要学习的设定下，后果比一次误判严重得多，"
       "因为策略会朝着这个方向持续优化。"
       "CDS 的做法是要求两类相互独立的证据同时支持这次提交。")

    # 3.4 SPO 的过渡
    rw("前三个模块构成了一个可以安全试错的环境",
       "前三个模块构成了一个可以安全试错的环境，余下的问题是如何利用这个环境改进决策。"
       "设计这一模块的动机来自一个实测观察。"
       "在固定规则的版本中，被否决后更换动作重试的净效果为负，"
       "更换后的动作改善与恶化之比不足首次提议的十分之一。"
       "原因在于固定规则把最有把握的动作排在首位，此后的备选顺序与窗口特性无关，"
       "更换因而往往是盲目的。序贯决策本身可行，问题出在备选顺序需要根据窗口类型学习。")

    # 第 6 章章首
    rw("本章记录当前实现中遇到的主要问题",
       "方法与实验规划给出的是打算做到什么，本章记录实际做的过程中遇到了什么。"
       "已发现的问题分三类，一类是实现缺陷，改正之后现象消失，"
       "一类是设计取舍带来的固有限制，改不掉只能说明，"
       "另一类源于实验设计本身，需要重新安排对照才能回答。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"文字润色完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
