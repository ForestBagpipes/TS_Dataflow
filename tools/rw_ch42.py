# -*- coding: utf-8 -*-
"""Section 4.2. The eight experiment blocks all followed the same three sentence
template and each ended with an expected result. A planning chapter states the
setup, so the expectations are removed and each block is written to its own
shape."""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260819.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    rw("设计目标是确认本文问题设定成立",
       "这一组用来确认问题设定成立，即模型行为信号在部分干净数据上会给出与有害性相反的读数。"
       "干净分布外层由随机游走、阶梯、脉冲串与锯齿四种合成形态构成，"
       "真实跨域层取自 Exchange 且不做注入，两组数据都是干净的且都属于分布外。"
       "按形态分别统计行为风险的分布并作对照，若信号度量的是可预测程度而非质量，"
       "两组的读数会分居两端。同时统计各层的编辑经济学，"
       r"即每破坏单位方差换到的效用增益，$\Delta U/\Delta\mathrm{Var}$。")

    rw("设计目标是检验本文最核心的机制主张",
       "这一组检验本文最核心的机制主张，即屏蔽通过决定哪些奖励到达策略来塑造策略的行为。"
       "训练两个策略，一个以未经过滤的效用变化为奖励，另一个以屏蔽后的奖励为奖励，"
       "两者共享相同的状态构建、动作空间与学习算法，唯一差别在奖励定义。"
       "记录两者在受保护层上提出抹平类动作的频率随训练轮次的变化，"
       "以及训练结束时的受保护层误编辑数。"
       "该实验属消融，只含本文方法的两个变体，不含基线。")

    rw("设计目标是验证定理 3",
       "这一组验证定理 3，即学习过程本身不破坏语料。"
       "对比两种训练方式，一种把动作直接作用于原数据后再评估，"
       "代表已有强化学习清洗方案的做法，另一种采用本文的沙箱执行。"
       "统计训练全过程中累计造成的损害随交互次数的变化，"
       r"并扫描探索系数 $c_{u}$ 观察两种方式的差距如何随探索强度变化。"
       "表中同时列出全部基线在同一语料上的最终损害作为参照行。")

    rw("设计目标是量化策略学习相对于固定规则的改进",
       "这一组量化策略学习相对于固定规则的改进，"
       "并检验早期版本中重试失效的原因是否为策略无法适应窗口类型。"
       "比较随机策略、固定规则策略、本文的学习策略以及知晓真值的理想策略，"
       "四者共用同一屏蔽与同一动作空间，并在语料层协议下与全部基线同表比较。"
       "除总体指标外，单独统计被否决后更换动作的成功率，与固定规则版本的结果对照。"
       "由于经屏蔽裁决的候选中接受率本身不高，即使最有利的画像簇也只有约两成通过，"
       "策略学习的收益主要来自抑制无望提议而非提高修复量，"
       "损害与修复上的改善预计温和，主要差距应出现在预算效率一组。")

    rw("设计目标是检验按价值分配探测预算是否优于均匀分配",
       "这一组检验按价值分配探测预算是否优于均匀分配。"
       "固定语料总预算，比较均匀分配、按风险分数分配与本文按价值估计分配三种方式。"
       "曲线的横轴取计算开销而非探测次数，这样打分族可以一并参与，"
       "因为 Data Shapley 需要反复重训、TimeInf 需要海森向量积、本文的探测只做前向，"
       "三者的单位开销不同，按探测次数比较对打分族没有意义。"
       "按探测次数的版本另行给出，用于本文方法内部三种分配方式的对比。"
       "同时统计被跳过窗口的构成，核对跳过的是否确实是后验确定且指向干净的窗口。")

    rw("设计目标是对标两类替代裁决机制",
       "这一组对标两类替代裁决机制。固定策略与候选批次，"
       "分别施加软惩罚、本文的硬屏蔽与只对效用标定的单信号屏蔽，"
       "扫描各自的参数得到损害与修复的前沿曲线。"
       "软惩罚把结构失真作为目标函数中的一项，效用增益足够大时结构惩罚可以被抵消，"
       "单信号屏蔽唯一能压低损害的方式是提高效用门槛，"
       "两者与硬屏蔽的差别应当在严格的损害预算区间内显现。")

    rw("设计目标是验证屏蔽与策略学习可以外挂到不同的动作来源上",
       "这一组验证屏蔽与策略学习可以外挂到不同的动作来源上。"
       "把提议者依次替换为随机策略、SCREEN、IMR、MTCSC 的单变量分支以及本文自身的策略，"
       "各自比较接入前后的指标变化。"
       "若屏蔽的行为随输入变化而非一律保守，"
       "则降幅应当随提议者候选质量的下降而增大。")

    rw("设计目标是量化各模块的边际贡献",
       "这一组量化各模块的边际贡献并检验方法对超参数的稳健性。"
       "消融包含无屏蔽、无效用条件、无结构条件、无同类校准、无策略学习、"
       "无预算分配与完整方法七档，每档报告损害与修复两栏，"
       "并额外报告每次编辑的平均损害与平均修复，以消除编辑数差异的干扰。"
       r"敏感性部分扫描目标损害率 $\alpha$ 与探索系数 $c_{u}$，"
       "并对照代理模型与真实基础模型两种探测器。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"4.2 八组实验改写完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
