# -*- coding: utf-8 -*-
"""Steps six and seven of the introduction.

The method paragraph and the figure caption were two separate objects, one
naming four modules and the other describing two waveforms, with nothing joining
them. They are joined here, the figure is read through the modules that produce
the two opposite verdicts. The contributions then answer the three costs named
in the limitation paragraph, one at a time and in the same order.
"""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 第六步 引出，与图 1 绑定
    rw("让判断发生在执行之后",
       "把判定移到执行之后，就不再需要事先写出只关于算子与参数的安全规则，"
       "因为这时可以直接看到修改造成的后果。"
       "移动判定的前提是执行可以撤回，否则判定为有害时已经无法挽回，"
       "本文因此把候选动作施加在工作副本的拷贝上，原副本只在判定通过时才被替换。"
       "这一个决定引出两个随之而来的问题。")

    rw("按照这一思路，本文提出屏蔽强化学习驱动的时序数据治理智能体",
       "按照这一思路，本文提出屏蔽强化学习驱动的时序数据治理智能体 IntroAct-TS，"
       "把治理建模为带预算的受约束序贯决策，"
       "一次决策依次经过取证、试执行、判定与学习四个环节。"
       "图 1 用一对窗口说明这一过程如何分开两种表面相似的情形。")

    rw("图 1 中的两个窗口来自同一份语料",
       "图 1 中的两个窗口来自同一份语料，波形上几乎一致。"
       "上方是传感器故障造成的孤立尖峰，下方是一次真实发生的极端峰值。"
       "两个窗口先由状态构建从自身统计画像与冻结模型的行为反应中取证，"
       "随后由沙箱重测把去尖峰算子施加在副本的拷贝上，原数据在此期间保持不变。"
       "重测显示两次编辑都让模型误差下降，"
       "因此仅凭效用读数无法把它们分开，抹平极值同样会让模型更容易预测。"
       "判定环节因而在效用之外核验编辑前后的局部结构是否保持一致，"
       "上方窗口的尖峰属于孤立扰动，去掉之后邻域形态不变，判定通过并提交，"
       "下方窗口的峰值与前后走势连成一体，削平之后局部结构显著改变，判定不通过并撤回。"
       "试执行与双信号判定的组合使得同一个算子在两个窗口上得到相反的裁决，"
       "而这一对裁决同时成为策略的反馈，"
       "使它在后续遇到相似窗口时不再提出会被撤回的动作。")

    # 第七步 贡献，一对一回应
    rw("贡献. 本文的主要贡献如下：",
       "上述三条路线的代价各自对应本文的一项工作，主要贡献如下。")

    rw("（1）把时序数据治理形式化为屏蔽约束下的序贯干预决策",
       "（1）针对判定时刻与执行时刻重合导致选错即破坏，"
       "本文把时序数据治理形式化为屏蔽约束下的序贯干预决策，并给出对应的智能体 IntroAct-TS。"
       "该形式化把判定推迟到动作执行之后，动作在副本上试执行，判定通过才提交，"
       "因而不要求事先写出只关于动作本身的安全规则。"
       "每一次判定同时成为策略可用的反馈，"
       "安全与学习在这一设计中出自同一个决定，两者共用一次判定。")

    rw("（2）给出判定所需的双信号合取判据及其理论性质",
       "（2）针对能报告效果的仪器只有模型而模型在被抹平的数据上给出相反读数，"
       "本文给出判定所需的双信号合取判据及其理论性质。"
       "结构条件完全不看模型意见，因而能够拦下通过抹平序列换取低误差的动作，"
       "其阈值由共形风险控制标定，使提交编辑的损害率获得有限样本的分布无关保证。"
       "本文进一步证明，把结构约束写成目标函数中的惩罚项时损害率存在不可消除的下界，"
       "而写成合取条件时没有这个下界，两种写法因此并不等价。")

    rw("（3）证明策略学习不以破坏语料为代价",
       "（3）针对探索期的错误会真实落在语料上，"
       "本文证明策略学习不以破坏语料为代价，并刻画了保证随学习推进的退化速率。"
       "由于候选动作在副本上执行且提交需经判定，"
       "对任意策略与任意探索强度，被提交编辑的结构失真都受同一阈值约束，"
       "未通过判定的尝试不留下任何痕迹。"
       "策略更新会改变候选分布从而削弱共形标定所依赖的可交换性，"
       "本文给出两次标定之间保证退化的上界，"
       "它与标定间隔成正比、与已积累的访问次数成反比，为重新标定的频率提供了定量依据。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"引言第六第七步完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
