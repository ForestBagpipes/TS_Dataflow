# -*- coding: utf-8 -*-
"""Chapter three's prose, and chapters four through six."""
import sys
sys.path.insert(0, "tools")
import docx
from docx_rewrite import count_math, find_paragraph, set_paragraph_md

PATH = "docx/胡宏彬-进度文档-20260820.docx"


def main():
    d = docx.Document(PATH)
    before = count_math(d)

    def rw(prefix, md):
        set_paragraph_md(d.paragraphs[find_paragraph(d, prefix)], md)

    # 3.1
    rw("缺少质量标签时单一证据存在盲区",
       "没有质量标签的时候，任何一路证据都有看不见的地方，"
       "所以 CDP 从两处取证，而这两处的盲区恰好错开。")
    rw("第一类证据是统计画像",
       r"头一路是统计画像 $p\in\mathbb{R}^{12}$，从窗口自身算出来，"
       "覆盖缺失率、异常密度、趋势强度、季节强度、频谱特征、平稳性、变点数量和复杂度，"
       "其中变点数量由线性代价的变点检测算法给出[27]。"
       "这些量对留下局部痕迹的噪声很敏感，尖峰会把异常密度顶上去，缺失片段会把缺失率顶上去。"
       "它看不见的是统计上完全正常的那类问题，重复片段就是，"
       "被复制的那一段和原段的统计属性一模一样。")
    rw("第二类证据是冻结基础模型的行为签名",
       r"第二路是冻结基础模型的行为签名 $b$，反映模型处理这个窗口时费不费劲。"
       "重复片段虽然统计正常，却会让模型在第二次遇到时给出反常自信的预测，"
       "这种反常在签名上留得下痕迹。"
       "行为证据看不见的是数据有问题和数据本身复杂之间的区别，两者都会让模型表现变差。")
    rw("把两类证据直接相加",
       "两路证据直接相加只会让盲区叠起来，因为它们的量纲和分布都不一样。"
       r"CDP 的做法是先在画像空间里找出与当前窗口最像的 $K$ 个邻居 $\mathcal{N}(x)$，"
       "相似度用画像向量做 L2 归一化之后的余弦距离衡量，"
       "再拿这组邻居的中位数与四分位距对行为签名做稳健标准化")
    rw("检索到的邻居集合还有第二个用途",
       r"找出来的这组邻居还有另一个用处。它们定义了一个画像簇 $j$，"
       "SPO 的动作价值估计正是按簇维护的。"
       "同一簇里的窗口结构相近，某个算子在其中一个上管用，往往在其余几个上也管用。"
       "CDP 因此既提供状态，也提供了策略赖以泛化的划分。算法 1 给出完整流程。")

    # 3.2
    rw("状态说明了窗口可能存在什么问题",
       "状态说明了这个窗口可能有什么毛病，却没说某个具体动作做下去会怎样。"
       "要回答这个只能真做一次再看结果。"
       "而强化学习又要反复地做，语料改过之后没法还原，两个要求正面冲突。"
       "SIR 把执行和提交拆开，让这两件事可以同时成立。")
    rw("候选动作作用在工作副本的拷贝上",
       r"候选动作作用在工作副本的拷贝上，得到候选窗口 $c=a(x')$，原副本 $x'$ 不动。"
       r"随后拿事前用过的那个探测函数原样测一遍 $c$，得到 $U(c)$，"
       r"与 $U(x')$ 相减就是这次动作带来的效用变化。"
       "这个读数有两个去处，一是送进 CDS 当裁决依据，二是裁决之后当策略更新的奖励。"
       "两个用处都要求读数在不同窗口和不同轮次之间可比，下面的引理给出具体条件。")
    rw("引理 1 对 SIR 的实现提出两条约束",
       "引理 1 落到实现上就是两条约束。"
       "归一化尺度取分块四分位距的中位数并在决策开始时定死，"
       "这样即使窗口里有整段水平位移，尺度也不会被它撑大。"
       "改变窗口长度的动作只在共有的重叠区间上比较，避免留出跨度发生变化。"
       r"这两条都满足了，同一个 $\Delta U$ 才既撑得起裁决又撑得起学习。")
    rw("SIR 还负责把裁决结果转换为奖励",
       "SIR 还负责把裁决结果换算成奖励。"
       "通过的动作按它的效用增益计正奖励，被撤销的只计探测代价形成负奖励，"
       "保留和拒绝处理都计零。"
       "这样一来策略在提动作的时候要同时掂量两件事，"
       "这个动作能带来多少改善，以及它有多大把握通过屏蔽。"
       "3.3 节会说明，正是后一件让策略绕开了拿抹平换效用这条捷径。")

    # 3.3
    rw("SIR 给出了可比的效用读数",
       "SIR 给出了可比的效用读数，而 2.2 节已经讲过这个信号在一部分数据上与有害性反着走。"
       r"只凭 $\Delta U$ 作裁决，会把那些靠削平序列换低误差的动作放进来。"
       "在策略要学习的设定下，后果比误判一次严重得多，因为策略会顺着这个方向一直优化下去。"
       "CDS 的办法是要求两路彼此独立的证据同时点头。")
    rw("定理 1 不依赖任何一个条件的判别力",
       "定理 1 不依赖任何单个条件的判别力。"
       "就算效用条件在某类数据上完全失灵，"
       "复合屏蔽造成的损害也不会超过只用结构条件时的水平。"
       "这个结论说的是损害总量，接受集缩小的同时修复收益也会跟着减少，"
       "两者怎么权衡由 3.4 节末尾的阈值标定处理。")
    rw("把结构信息以合取条件的形式引入",
       "把结构信息写成合取条件，跟把它写成目标函数里的一项惩罚，差别不止在形式上。"
       "同期的清洗智能体用的是后一种，"
       "在效用增益里减去带系数的结构失真，再按这个加权和排序取舍。"
       "下面的结论说明这两种写法在严格的损害预算下并不等价。")
    rw("屏蔽的第二重作用来自它与奖励的耦合",
       "屏蔽的第二重作用来自它和奖励之间的耦合。"
       "按 3.2 节的奖励定义，只有通过屏蔽的动作才计正奖励，被撤销的只留下探测代价。"
       r"策略实际收到的回报因此是过了结构条件之后的 $\Delta U$，不是原始读数。"
       "一个抹平动作就算拿到很高的效用读数，也会因结构失真超限而被撤销，最后计成负奖励。"
       "几轮之后策略会学到，在需要保护的窗口上提抹平动作是不划算的，"
       r"于是在提议阶段就绕开这类动作。若把奖励换成没过滤的 $\Delta U$，"
       "同样的学习过程会得到相反的结果。这一对照就是 4.2 节奖励塑形消融实验的设计依据。")
    rw("裁决之后的控制流有五个去向",
       "裁决之后有五种走法。"
       "三个条件都满足就接受，把候选副本提交为新的工作副本并记进轨迹。"
       "效用没改善或者结构失真超限就撤销，恢复原副本，并把撤销的原因写进状态。"
       "还有可信候选且预算没耗尽时可以换个动作再试，"
       "这时策略能依据撤销原因调整方向，"
       "被结构条件否掉意味着该换个动静更小的算子，"
       "被效用条件否掉则意味着对缺陷类型的判断可能就错了。"
       "窗口风险高但修不可靠时转入隔离，证据不足或预算耗尽时拒绝处理并结束这个窗口。"
       "算法 2 给出完整流程。")

    # 3.4
    rw("前三个模块构成了一个可以安全试错的环境",
       "前三个环节合起来是一个可以安全试错的场子，剩下的问题是怎么利用它把决策做得更好。"
       "这一模块的设计动机来自一次实测。"
       "在固定规则的版本里，被否决之后换动作重试的净效果是负的，"
       "换过之后的动作，改善与恶化之比不到首次提议的十分之一。"
       "原因在于固定规则把最有把握的动作排在最前，后面的次序与窗口特性无关，"
       "换来换去因此往往是盲目的。序贯决策本身没问题，问题出在备选次序需要按窗口类型学。")
    rw("SPO 采用上下文老虎机",
       "SPO 用的是上下文老虎机，理由是这个任务的决策序列很短，"
       "多数窗口三步以内结束，状态经 CDP 提取之后维度不高，动作集合也有限。"
       "在这种规模下，上置信界方法的样本效率和可解释性都好过需要大量交互的深度方法，"
       "遗憾分析也是现成的[18,19,20]。")

    # 4 章首
    rw("本文的做法建立在几个需要检验的判断之上",
       "本文的做法压在几个还需要验证的判断上。"
       "模型给出的效用读数在需要保护的数据上与有害性反着走，这是引入结构条件的前提。"
       "判定结果拿来当奖励能把策略引向那些通得过结构检验的修复方式，这是屏蔽的第二重职责。"
       "试错发生在副本上所以学习不伤语料，这是把判断后移换来的好处。"
       "本章的实验就围绕这几点安排，"
       "前四组看治理之后语料的质量够不够，后五组看智能体自己的决策靠不靠得住。"
       "在此之前先交代数据、噪声注入、基线和指标怎么定。")

    # 6.2
    rw("把策略从按画像簇维护的表格式价值估计升级",
       "把策略从按画像簇维护的表格式价值估计换成线性或浅层函数逼近，"
       "让它能用上状态里的连续分量，同时保住可解释性和样本效率。")

    d.save(PATH)
    d2 = docx.Document(PATH)
    print(f"第 3 章与第 4 章章首完成，公式 {before} -> {count_math(d2)}")


if __name__ == "__main__":
    main()
